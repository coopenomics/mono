export interface DocumentSignStepProps {
  /** Готовый HTML документа; вместо него можно передать `build`. */
  html?: string;
  /** Собрать экземпляр документа; возвращает HTML для чтения. */
  build?: () => Promise<string>;
  /** Пояснение над документом. */
  description?: string;
  /** Предупреждение над документом, например причина отказа председателя. */
  notice?: string;
  /** Подпись флажка согласия; по умолчанию «Я прочитал документ». */
  agreeLabel?: string;
  /** Подпись основной кнопки; по умолчанию «Подписать». */
  actionLabel?: string;
  /** Подпись кнопки назад; без неё кнопки нет. */
  backLabel?: string;
  /** Действие идёт: кнопка с лоадером, флажок заперт. */
  busy?: boolean;
  /** Подписывать пока нечего — шаг ждёт своё значение. */
  signDisabled?: boolean;
}
