/**
 * Блок кода: команда терминала либо фрагмент файла.
 *
 * Тёмная плашка с моноширинным текстом, копирование — значком в правом
 * верхнем углу блока. Длинная строка переносится, а не уезжает за край.
 */
export interface CodeBlockProps {
  /** Текст блока; переводы строк сохраняются. */
  value: string;
  /** Подпись над блоком («Команда», «Фрагмент package.json»). */
  label?: string;
  /** Пояснение под блоком: чем команда заканчивается, что поменять во фрагменте. */
  note?: string;
  /** Значок копирования в углу блока. По умолчанию включён. */
  copyable?: boolean;
}
