export interface DocumentSignSheetProps {
  /** Название документа — заголовок карточки. */
  title: string;
  /** Пояснение под названием: что даёт подпись. */
  subtitle?: string;
  /** Сформированный документ (html фабрики). Пусто — документа ещё нет. */
  html?: string | null;
  /** Документ формируется. */
  loading?: boolean;
  /** Документ сформировать не удалось — показать ошибку и «Повторить». */
  error?: boolean;
  /** Подпись идёт: кнопка крутится и не нажимается. */
  signing?: boolean;
  /** Подпись кнопки, например «Подписать договор». */
  signLabel: string;
  /** Текст на время формирования документа. */
  loadingText?: string;
  /** Текст ошибки формирования. */
  errorText?: string;
}
