export interface TablePagerProps {
  /** Текущая страница, счёт с единицы. */
  page: number;
  /** Сколько строк на странице просит экран. */
  rowsPerPage: number;
  /** Сколько строк всего в реестре — это знает бэкенд. */
  rowsNumber: number;
  /**
   * Как назвать строки в подписи диапазона: «Заказы 1–50 из 120».
   * По умолчанию — «Строки».
   */
  label?: string;
}
