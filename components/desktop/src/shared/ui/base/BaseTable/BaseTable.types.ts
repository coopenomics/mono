export interface BaseTableColumn<T = Record<string, unknown>> {
  /** Ключ поля в строке данных или произвольный id */
  key: string;
  /** Заголовок колонки */
  label: string;
  /** Выравнивание содержимого */
  align?: 'left' | 'right' | 'center';
  /** Поле строки, по которому достать значение (по умолчанию = key) */
  field?: keyof T | ((row: T) => unknown);
  /** Числовая колонка (правое выравнивание + tabular-nums) */
  numeric?: boolean;
  /**
   * Фиксированная ширина колонки, например `'160px'`. Вместе с `minWidth`
   * таблицы даёт предсказуемую сетку: колонки не схлопываются, а на узком
   * экране включается горизонтальная прокрутка вместо наезжающих ячеек.
   */
  width?: string;
  /** Колонку можно сортировать кликом по заголовку. */
  sortable?: boolean;
  /** Своё сравнение (по умолчанию сравниваются значения поля). */
  sort?: (a: unknown, b: unknown, rowA: T, rowB: T) => number;
  /**
   * Не переносить содержимое ячейки по словам. По умолчанию таблица переносит:
   * длинное наименование уходит на вторую строку, а не вылезает на соседнюю
   * колонку. Ставить там, где разрыв меняет смысл — код, дата, идентификатор.
   */
  nowrap?: boolean;
}

export interface BaseTableProps<T = Record<string, unknown>> {
  columns: BaseTableColumn<T>[];
  rows: T[];
  /**
   * Уникальный ключ строки: имя поля либо функция, когда ключ составной
   * (например «наименование + причина» у позиций списания, где своего
   * идентификатора у строки нет).
   */
  rowKey?: keyof T | ((row: T) => string);
  /**
   * Оставлен для совместимости вызовов и ни на что не влияет: отклик строки на
   * наведение включает `clickableRows`. Подсветка — обещание, что по строке
   * можно нажать, и на реестре без перехода она сбивает с толку (стол
   * поставщика, 14.09.2026: партия обводилась рамкой, нажатие ничего не
   * делало). Новым экранам признак не нужен.
   */
  hover?: boolean;
  /**
   * Загрузка. Канон запрещает спиннер поверх контента, поэтому вместо строк
   * рисуется каркас В ТОЙ ЖЕ таблице: ширины колонок совпадают по определению,
   * и при появлении данных ничего не прыгает. Уже показанные строки каркасом
   * не заменяются — обновление проходит молча.
   */
  loading?: boolean;
  /** Сколько строк каркаса показать при загрузке. */
  skeletonRows?: number;
  /** Минимальная ширина таблицы; ниже неё включается горизонтальная прокрутка. */
  minWidth?: string;
  /** Заголовок прилипает к верху при вертикальной прокрутке. */
  stickyHeader?: boolean;
  /** Максимальная высота области прокрутки, например `'60vh'`. */
  maxHeight?: string;
  /** Колонка начальной сортировки (ключ из `columns`). */
  sortBy?: string;
  /** Начальная сортировка по убыванию. */
  descending?: boolean;
  /**
   * Выбор строк галочками в первой колонке — для действий над пачкой записей
   * (напечатать отмеченные, отправить отмеченные). `multiple` добавляет в
   * заголовок галочку «выбрать все видимые».
   *
   * Сам список выбранного живёт на странице: только она знает, что с ним
   * делать и когда сбрасывать.
   */
  selection?: 'multiple' | 'single' | 'none';
  /** Выбранные строки, `v-model:selected`. */
  selected?: T[];
  /**
   * Строка открывает сущность по нажатию: курсор-указатель и событие
   * `row-click`. Куда вести, знает экран — таблица отдаёт только строку. Без
   * этого признака нажатие по строке ничего не делает.
   *
   * Функция — когда открывается не всякая строка: в ленте движений по кошельку
   * заказ стоит не за каждой операцией, и обещать переход там, где его нет,
   * нельзя. Курсор и событие достаются ровно тем строкам, на которых функция
   * вернула `true`.
   */
  clickableRows?: boolean | ((row: T) => boolean);
}
