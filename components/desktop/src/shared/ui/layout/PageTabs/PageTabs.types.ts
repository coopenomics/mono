import type { InjectionKey } from 'vue';
import type { RouteLocationRaw } from 'vue-router';

/**
 * Признак «в этом каркасе есть место для поднятых вкладок». Раздаётся
 * каркасом приложения и читается синхронно, до первого рендера полосы.
 *
 * Искать место в документе на монтировании нельзя: каркас в этот момент ещё
 * не вставлен, телепорт запоминает пустую цель, а последующее включение
 * роняет отрисовку страницы (`insertBefore` у null) — маршрут падал целиком,
 * и вкладки оставались внутри страницы вместе с её отступами.
 */
export const PAGE_TABS_HOST: InjectionKey<boolean> = Symbol('page-tabs-host');

export interface PageTab {
  /** Уникальный ключ — выбирается через `activeKey` */
  key: string;
  /** Подпись таба */
  label: string;
  /** Иконка слева от подписи (Material Icons) */
  icon?: string;
  /** Счётчик справа (число записей в этом разделе) */
  count?: number | string;
  /** Маршрут — если задан, рендерится как router-link */
  route?: RouteLocationRaw;
  /**
   * Имя маршрута вместо готовой ссылки. Таб сам переходит на него, сохраняя
   * параметры текущего маршрута, и сам считает себя активным по `route.matched`
   * — в том числе когда открыт дочерний маршрут. Так устроены разделы-оболочки
   * с `<router-view>` внутри (отчётность, магазин расширений).
   */
  routeName?: string;
  /** Отключённый таб */
  disabled?: boolean;
}

export interface PageTabsProps {
  /** Список вкладок */
  tabs: PageTab[];
  /**
   * Поднять полосу вкладок под шапку, над содержимым страницы (телепорт в
   * `#page-tabs-host`). Так она идёт во всю ширину окна и не зависит от
   * боковых отступов страницы: раньше страницы растягивали её отрицательными
   * отступами, из-за чего полоса вылезала за экран и появлялась
   * горизонтальная прокрутка. Ставится там, где вкладки — основная навигация
   * раздела; вложенные вкладки внутри страницы оставляют на месте.
   */
  hoist?: boolean;
  /**
   * Ключ активной вкладки. Не задаётся для табов с `routeName` — там
   * активность определяется по текущему маршруту.
   */
  activeKey?: string;
}
