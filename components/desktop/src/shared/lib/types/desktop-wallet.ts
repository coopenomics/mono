import type { WalletProgram } from 'src/shared/ui/domain/WalletCard';

/**
 * Декларация кошелька, который расширение «приносит» на стол пайщика
 * (страница кошелька). Путь B: каждое расширение объявляет свои кошельки
 * по идентификатору (`wallet_name`), реестр собирает объединение деклараций
 * установленных расширений и core-декларации, дедупит по `wallet_name`
 * (пересеклись — остаётся первое вхождение) и рендерит карточки.
 *
 * Балансы тянутся отдельно по `wallet_name` из `getUserWallets`
 * (сырой срез `ledger2::userwallets`, без сворачивания паевого и членского).
 */
export interface DesktopWalletCard {
  /** Идентификатор кошелька (`eosio::name`) — ключ дедупликации и сопоставления с балансом. */
  wallet_name: string;
  /** Наименование карточки (UI). */
  label: string;
  /** Дополнительная подпись под заголовком. */
  description?: string;
  /** Визуальный акцент плитки-иконки (`--prog-*`). По умолчанию 'wallet'. */
  accent?: WalletProgram;
  /** Material-иконка карточки. */
  icon?: string;
}
