import DOMPurify from 'dompurify';

/**
 * Очистка документа перед показом в кабинете.
 *
 * Шаблоны документов собираются с выключенным автоэкранированием — это
 * осознанно, часть данных кооператива приходит с разметкой. Оборотная сторона:
 * имя, адрес или название организации с угловыми скобками становятся
 * разметкой, и документ, открытый на экране, выполнил бы её как свою.
 *
 * Профиль намеренно широкий: здесь показывают документ, а не заметку, — нужны
 * таблицы, выравнивание, собственные стили шаблона. Поэтому `<style>`
 * сохраняется, а вместе с ним и вид документа: вырезать его значило бы
 * поменять то, как выглядят уже подписанные заявления.
 *
 * `WHOLE_DOCUMENT` обязателен: без него DOMPurify оставляет сам тег `<style>`,
 * но стирает его содержимое (проверено эмпирически, см. BaseDocument.vue). В
 * этом режиме результат приходит обёрнутым в `<html><head>…</head><body>…`, и
 * это безвредно — при вставке через `innerHTML` браузер разбирает обёртку по
 * алгоритму разбора фрагмента и самих тегов не создаёт, а содержимое остаётся.
 *
 * Чего профиль не ловит: правила CSS внутри `<style>` остаются как есть. Это
 * несравнимо слабее выполнения скрипта и живёт ровно до включения
 * автоэкранирования в самой фабрике — оно правильно по существу, но сдвигает
 * хэши всех документов, по которым сверяются подписи, и потому идёт отдельным
 * релизом с поднятием версий шаблонов.
 */
export function sanitizeDocumentHtml(html: string | null | undefined): string {
  if (!html) return '';
  return DOMPurify.sanitize(html, {
    ADD_TAGS: ['style'],
    ADD_ATTR: ['class', 'id'],
    WHOLE_DOCUMENT: true,
  });
}
