/**
 * Сравнивает контрольные суммы документов.
 *
 * Регистр в шестнадцатеричной записи ничего не значит, но по дороге меняется:
 * цепь отдаёт хэш заглавными, журнал узла хранит его так, как он пришёл в теле
 * события, а локальный пересчёт возвращает то, что вернул браузерный crypto.
 * Строгое сравнение строк из-за этого объявляет совпадающие документы разными —
 * и пользователь видит «локально пересчитанный хеш не совпадает» на исправном
 * документе.
 *
 * Пустое значение с любой стороны — не совпадение: сверять нечего.
 */
export function sameHash(left?: string | null, right?: string | null): boolean {
  if (!left || !right) return false;
  return left.toLowerCase() === right.toLowerCase();
}
