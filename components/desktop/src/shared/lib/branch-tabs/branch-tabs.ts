import { markRaw, shallowReactive, type Component } from 'vue';
import type { ChainTableRef } from 'src/shared/lib/realtime';

/**
 * Вкладка приложения на странице кооперативного участка.
 *
 * Компонент вкладки получает один параметр — `braname` — и сам читает свои
 * данные своим запросом. Стол «Кооперативный участок» о содержимом вкладки
 * ничего не знает.
 */
export interface BranchTabEntry {
  /** Стабильный ключ вкладки `<приложение>:<вкладка>` — он же значение `?tab=` в адресе. */
  id: string;
  /** Имя приложения (`extension_name` стола). Вкладка видна, только когда приложение установлено в кооперативе. */
  extension: string;
  /** Подпись вкладки. */
  label: string;
  /** Значок вкладки (Material Icons). */
  icon?: string;
  /** Содержимое вкладки; параметр — `braname`. */
  component: Component;
  /**
   * Вовлечён ли участок в приложение: подключён как пункт выдачи, имеет
   * инициаторов и т.п. Невовлечённый участок вкладку не получает. Отказ или
   * ошибка запроса читаются как «не вовлечён» — чужое приложение не должно
   * ломать страницу участка.
   */
  isInvolved: (braname: string) => Promise<boolean>;
  /** Таблицы ленты изменений, по которым вовлечённость перечитывается. */
  liveTables?: ChainTableRef[];
}

/**
 * Реестр: вкладки приложений на странице кооперативного участка.
 *
 * Зачем: участок может быть пунктом выдачи Стола заказов, площадкой проката
 * или чем-то ещё, а стол «Кооперативный участок» от этих приложений не
 * зависит. Приложение объявляет вкладку из своего `install.ts` — там же, где
 * добавляет в ядро маршруты и оверлеи (`registerGlobalOverlay`), — а страница
 * участка рисует реестр обобщённо, ничего конкретного не импортируя.
 *
 * `install.ts` выполняется у всех приложений сборки, поэтому установленность
 * приложения в кооперативе проверяет страница участка — по столам, которые
 * отдал сервер.
 */
const tabs = shallowReactive<BranchTabEntry[]>([]);

/** Объявить вкладку участка. Идемпотентно по `id`: повторная установка приложения дублей не даёт. */
export function registerBranchTab(entry: BranchTabEntry): void {
  if (tabs.some((tab) => tab.id === entry.id)) return;
  tabs.push({ ...entry, component: markRaw(entry.component) });
}

/** Объявленные вкладки реактивным списком — для страницы участка. */
export function getBranchTabs(): BranchTabEntry[] {
  return tabs;
}
