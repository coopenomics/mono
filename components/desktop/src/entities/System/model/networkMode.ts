import { computed } from 'vue';
import { useSystemStore } from './store';

/**
 * Роли сети на столе — одно определение на весь стол (утверждено 28.11.2026).
 *
 * ВЕДУЩИЙ — кооператив, который запустил цепь и ведёт сеть: назначает
 * операторов, регистрирует кооперативы. Ведущий в сети один; его имя узел
 * читает из цепи и сообщает столу (`network_lead`).
 *
 * ОПЕРАТОР — кооператив, которого ведущий назначил подключать другие
 * кооперативы и обслуживать их. Операторов в сети может быть несколько. Узел
 * сообщает, назначен ли его кооператив оператором (`is_operator`): на узле
 * оператора есть реестр кооперативов и страницы подключения.
 *
 * ОПЕРАТОР КООПЕРАТИВА — оператор, который подключил кооператив узла:
 * `parent_username` его строки в реестре сети. Пусто — кооператив работает на
 * своей платформе.
 *
 * ПРОВАЙДЕР — внешний сервис каталога приложений, облачного хостинга и
 * подписок (`has_provider`, настройка узла `PROVIDER_BASE_URL`). Подключается
 * по желанию. Узел без провайдера показывает встроенные приложения: каталога
 * приложений и подписок у него нет.
 *
 * Имён кооперативов в коде стола нет: каждую роль называет узел.
 */
export function useNetworkMode() {
  const system = useSystemStore();

  /** Ведущий сети. */
  const networkLead = computed(() => system.info.network_lead || '');
  /** Кооператив узла — ведущий сети. */
  const isLead = computed(() => !!networkLead.value && system.info.coopname === networkLead.value);
  /** Кооператив узла назначен оператором: он подключает кооперативы. */
  const isOperator = computed(() => !!system.info.is_operator);
  /** Оператор, подключивший кооператив узла; `null` — кооператив на своей платформе. */
  const operator = computed(() => system.info.cooperator_account?.parent_username || null);
  /** Узел подключён к провайдеру: есть каталог приложений, хостинг и подписки. */
  const hasProvider = computed(() => !!system.info.has_provider);

  return { networkLead, isLead, isOperator, operator, hasProvider };
}
