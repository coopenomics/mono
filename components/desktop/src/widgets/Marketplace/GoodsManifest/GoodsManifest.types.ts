/** Строка накладной: что и сколько, уже в подписях единиц отпуска. */
export interface GoodsManifestLine {
  key: string;
  name: string;
  /** Количество в единицах отпуска: «10 упак. 1 л», «15 л». */
  quantity: string;
  /** Приглушённое дополнение к количеству: «3 кор.». */
  quantityNote?: string;
  /** Стоимость строки, отформатированная, с валютой. */
  cost?: string;
  /** Предупреждение под названием: недопоставка, ошибка этапа. */
  note?: string;
}

export interface GoodsManifestProps {
  /** Шапка накладной: «В поставке», «Привезёт», «К выдаче». */
  title: string;
  lines: GoodsManifestLine[];
  /** Подпись справа в шапке — обычно число позиций: «2 поз.». */
  count?: string;
}
