import { boot } from 'quasar/wrappers';

/**
 * Ошибки компонентов при серверной сборке — в журнал, а не исключением.
 *
 * Без своего обработчика Vue в режиме разработки бросает исключение прямо из
 * обработки ошибки компонента и не доходит до строки, которая снимает указатель
 * на текущий компонент. Указатель застревает на весь срок жизни процесса, и код
 * вне компонентов (инициализация в boot) начинает брать состояние того самого
 * запроса вместо своего: документы уходят с пустым состоянием, а данные одного
 * запроса могут попасть в документ другого. Свой обработчик возвращает Vue на
 * штатный путь: упавший компонент рисуется пустым, процесс остаётся здоровым,
 * в журнале видно, какую страницу чинить. На клиенте ничего не меняем.
 */
export default boot(({ app, ssrContext }) => {
  if (typeof window !== 'undefined') return;
  app.config.errorHandler = (err, instance, info) => {
    const name = instance?.$options?.name ?? instance?.$?.type?.__name ?? 'неизвестный компонент';
    const url = (ssrContext as { req?: { url?: string } } | null | undefined)?.req?.url ?? '';
    console.error(`[ssr] ошибка компонента «${name}» (${info}) на ${url}:`, err instanceof Error ? err.message : err);
  };
});
