import type { IGetSegmentsInput } from './types';

/**
 * Параметры запроса списка участников проекта или компонента.
 *
 * Список показывается целиком, без постраничного вывода, поэтому предел взят
 * с большим запасом — это максимум, который принимает сервер. Участников
 * заметно меньше даже у крупных проектов; если предел когда-нибудь станет
 * тесен, список нужно будет догружать по мере прокрутки, а не поднимать
 * число — большее сервер отклонит.
 */
export const CONTRIBUTORS_PAGE_OPTIONS: NonNullable<IGetSegmentsInput['options']> = {
  page: 1,
  limit: 1000,
  sortBy: '_created_at',
  sortOrder: 'DESC',
};
