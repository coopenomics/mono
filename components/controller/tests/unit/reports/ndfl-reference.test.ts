/**
 * Unit-тесты справочника налоговых параметров российской юрисдикции.
 *
 * Что здесь защищается. Форма 6-НДФЛ применяется с отчётности за 2025 год, и
 * за более ранние годы параметров в справочнике нет. Если бы справочник молча
 * отдавал сегодняшние ставки, генерация собрала бы внешне правильный файл с
 * чужими цифрами — ошибку такого рода замечают уже в налоговой. Поэтому за
 * неизвестный год справочник обязан отказывать, причём с причиной, а не
 * абстрактным «не найдено».
 *
 * Реестр случаев: test-registry/platform.jurisdictions.yaml
 */

import { getNdflParams } from '~/extensions/reports/domain/services/ndfl-reference';

describe('getNdflParams', () => {
  it('отдаёт параметры за год, с которого применяется форма', () => {
    const params = getNdflParams(2025);

    expect(params).toBeDefined();
  });

  // plt.jur.break.02
  it('отказывает за год, которого нет в справочнике, и называет причину', () => {
    // Не просто «бросает»: в тексте обязан быть и сам год, и то, с какой
    // отчётности форма применяется — иначе оператор не поймёт, что делать.
    expect(() => getNdflParams(2024)).toThrow(/2024/);
    expect(() => getNdflParams(2024)).toThrow(/2025/);
  });

  it('отказывает и за годы заведомо вне справочника', () => {
    expect(() => getNdflParams(1999)).toThrow();
  });
});
