/**
 * Реквизиты, по которым кассир перечисляет удержанный налог в бюджет.
 *
 * Реквизиты и само назначение платежа зависят от страны регистрации
 * кооператива: где-то это единый налоговый счёт, где-то — отдельный счёт по
 * каждому налогу или прямые реквизиты налогового органа. Поэтому набор
 * выбирается по стране, а не зашит в сервис; сегодня в системе зарегистрирован
 * только российский контур (`Country` знает одно значение), и реализация здесь
 * пока одна.
 *
 * Значения актуальны на август 2026: КПП получателя сменился 05.12.2025
 * (770801001 → 770701001) вместе с переездом МИ ФНС по управлению долгом, а с
 * 01.04.2026 назначением платежа по приказу Минфина № 58н служит аббревиатура
 * «ЕНП» — прежняя формулировка «Единый налоговый платеж» больше не канон.
 * Реквизиты меняются приказами, поэтому лежат одной таблицей: правится в одном
 * месте, а не по сервисам.
 */

/** Строка реквизита — как её увидит кассир в карточке платежа. */
export interface TaxRequisiteRow {
  label: string;
  value: string;
}

export interface TaxTransferRequisites {
  /** Назначение платежа: кассир копирует его в банк как есть. */
  memo: string;
  /** Получатель платежа. */
  recipientName: string;
  /** Остальные реквизиты — построчно, в порядке заполнения платёжного поручения. */
  rows: TaxRequisiteRow[];
}

/**
 * Единый налоговый платёж (Россия). Одни и те же реквизиты для всех регионов:
 * налог зачисляется на единый налоговый счёт, а разносит его по КБК уже сама
 * налоговая — по уведомлению об исчисленных суммах.
 */
const RUSSIA_ENP: TaxTransferRequisites = {
  memo: 'ЕНП',
  recipientName: 'Казначейство России (ФНС России)',
  rows: [
    { label: 'ИНН получателя', value: '7727406020' },
    { label: 'КПП получателя', value: '770701001' },
    {
      label: 'Банк получателя',
      value: 'ОКЦ № 7 ГУ Банка России по ЦФО//УФК по Тульской области, г. Тула',
    },
    { label: 'БИК', value: '017003983' },
    { label: 'Счёт банка получателя', value: '40102810445370000059' },
    { label: 'Казначейский счёт', value: '03100643000000018500' },
    { label: 'КБК', value: '18201061201010000510' },
    { label: 'ОКТМО', value: '0' },
    { label: 'Статус плательщика', value: '01' },
  ],
};

/** Страна регистрации кооператива → как он платит налог. */
const BY_COUNTRY: Record<string, TaxTransferRequisites> = {
  Russia: RUSSIA_ENP,
};

/**
 * Реквизиты перечисления налога для страны кооператива. Неизвестная страна —
 * не повод отказать кассиру в заявке: платёж создаётся с назначением, а
 * реквизиты кассир заполняет сам, как делал до появления этой таблицы.
 */
export function getTaxTransferRequisites(country?: string): TaxTransferRequisites | null {
  return BY_COUNTRY[country ?? 'Russia'] ?? null;
}
