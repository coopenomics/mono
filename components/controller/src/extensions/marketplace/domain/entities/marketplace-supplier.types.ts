/**
 * Реестр поставщиков «Стола заказов».
 *
 * Заменяет прежнюю концепцию whitelist (открытая витрина / по списку):
 * теперь ВСЕ поставщики проходят через реестр. Поставщик допускается к
 * публикации поставок только при `status = APPROVED`; до одобрения/при
 * отказе допуска нет. Каждый поставщик действует по договору (членскому
 * бумажному либо боевому ДУХД), номер и дата которого хранятся в записи и
 * попадают в назначение платежа при выплате.
 *
 * Модель — жёсткая развилка: смена модели требует переподписания договора
 * (членская → боевая: электронный ДУХД на платформе; боевая → членская:
 * бумажный договор с кооперативом + его реквизиты). На текущем этапе
 * реализована только членская модель; боевая — заглушка.
 */
export enum MarketplaceSupplierModel {
  /** Членская модель — бумажный договор с кооперативом (номер + дата). */
  MEMBERSHIP = 'membership',
  /** Боевая (паевая) модель — электронный договор участия в хоздеятельности. Заглушка. */
  SHARE = 'share',
}

export enum MarketplaceSupplierStatus {
  /** Заявка подана пайщиком, ожидает рассмотрения председателем. */
  PENDING = 'pending',
  /** Поставщик одобрен — допуск к публикации поставок открыт. */
  APPROVED = 'approved',
  /** Заявка отклонена — допуска нет. */
  REJECTED = 'rejected',
}
