/**
 * Фаза кооперативного участка по вложениям инициаторов в итоге месяца
 * (задача 99D-30, PRD компонента 68, раздел «Фазы»). Фиксируется при расчёте
 * итога по строке участка в цепи и дальше не меняется: история прогонов
 * показывает, в какой фазе участок прошёл каждый месяц.
 */
export enum MarketplacePeriodInvestPhase {
  /** У участка нет вложений инициаторов. */
  NONE = 'NONE',
  /** Фаза 1: месяц с недостачей — собранная обеспечительная часть целиком участку, недостачу покрывают вложения. */
  DEFICIT = 'DEFICIT',
  /** Фаза 2: доля инициаторов возмещает их использованные вложения. */
  REPAYING = 'REPAYING',
  /** Фаза 3: использованное возвращено, доля инициаторов направляется участку. */
  BRANCH = 'BRANCH',
}
