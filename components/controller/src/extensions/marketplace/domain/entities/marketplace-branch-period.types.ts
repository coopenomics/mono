/**
 * Фаза кооперативного участка по паевым взносам инициаторов в итоге месяца
 * (задача 99D-30, PRD компонента 68, раздел «Фазы»). Фиксируется при расчёте
 * итога по строке участка в цепи и дальше не меняется: история прогонов
 * показывает, в какой фазе участок прошёл каждый месяц.
 */
export enum MarketplacePeriodInvestPhase {
  /** У участка нет паевых взносов инициаторов. */
  NONE = 'NONE',
  /** Фаза 1: месяц с недостачей — собранная обеспечительная часть целиком участку, недостачу покрывают паевые взносы. */
  DEFICIT = 'DEFICIT',
  /** Фаза 2: доля инициаторов возмещает их использованные паевые взносы. */
  REPAYING = 'REPAYING',
  /** Фаза 3: использованное возвращено, доля инициаторов направляется участку. */
  BRANCH = 'BRANCH',
}
