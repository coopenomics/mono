/**
 * Ячейка хранения на складе кооперативного участка — адресуемое место с двумя
 * координатами: секция (столбец) и ярус (строка). Склад читается как таблица,
 * место находится по адресу, а не перебором ленты полок.
 *
 * Заменяет прежнюю свободную строку-подпись полки (`marketplace_inventory.shelf`).
 * В ячейке может стоять бокс, а может лежать негабаритное имущество напрямую.
 */
export interface MarketplaceStorageCellProps {
  id: string;
  coopname: string;
  /** Кооперативный участок, которому принадлежит ячейка. */
  braname: string;
  /** Координата-столбец: секция/стеллаж («A», «Холодильник»). */
  section: string;
  /** Координата-строка: ярус. Нумерация с 1. */
  level: number;
  /**
   * Человекочитаемый адрес ячейки («A-02»). Обычно выводится из координат, но
   * хранится явно: ячейки, перенесённые с прежних полок-строк, сохраняют
   * исходную подпись, чтобы у оператора не поехали привычные адреса.
   */
  code: string;
  /** Произвольная подпись оператора; NULL — достаточно кода. */
  label: string | null;
  /** Выведенная из оборота ячейка не предлагается при размещении. */
  is_active: boolean;
  created_at: Date;
  updated_at: Date;
}

/** Ярус, присваиваемый ячейкам, перенесённым с прежних полок-строк. */
export const MARKETPLACE_STORAGE_CELL_LEGACY_LEVEL = 1;

/**
 * Человекочитаемый адрес из координат: «A» + 2 → «A-02».
 *
 * Ярус дополняется до двух знаков, чтобы адреса одного стеллажа сортировались
 * лексикографически в том же порядке, что и численно.
 */
export function buildStorageCellCode(section: string, level: number): string {
  return `${section.trim()}-${String(level).padStart(2, '0')}`;
}
