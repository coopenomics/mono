import { calcNdflNet, calcNdflTax, ndflBreakdown, NDFL_RATE_PERCENT } from './ndfl.util';

/**
 * Расчёт удержания зеркалит `BranchNdfl` контракта. Разойтись они не должны:
 * кассир платит по расчёту бэкенда, а списывает с кошелька контракт — при
 * расхождении платёж повиснет, а разницу придётся разбирать вручную.
 */
describe('ndfl.util — удержание налога с материальной помощи', () => {
  it('ставка зафиксирована на 13 %', () => {
    expect(NDFL_RATE_PERCENT).toBe(13);
  });

  it('считает от суммы заявления: 10 000 → 1 300 налога и 8 700 на руки', () => {
    expect(calcNdflTax(10000)).toBe(1300);
    expect(calcNdflNet(10000)).toBe(8700);
  });

  it('разбивка сходится: начислено = удержано + к перечислению', () => {
    const { gross, tax, net } = ndflBreakdown(7777);
    expect(tax + net).toBe(gross);
  });

  describe('округление до полного рубля (п. 6 ст. 52 НК РФ)', () => {
    it('меньше 50 копеек — отбрасывается', () => {
      // 100 × 13 % = 13,00 ровно; 103 × 13 % = 13,39 → 13.
      expect(calcNdflTax(103)).toBe(13);
    });

    it('ровно 50 копеек — округляется вверх', () => {
      // 50 × 13 % = 6,50 → 7.
      expect(calcNdflTax(50)).toBe(7);
    });

    it('больше 50 копеек — округляется вверх', () => {
      // 107 × 13 % = 13,91 → 14.
      expect(calcNdflTax(107)).toBe(14);
    });

    it('на малой сумме округление заметно: с 10 ₽ удерживается рубль, не 1,30', () => {
      // 10 × 13 % = 1,30 → 1 ₽, на счёт уходит 9 ₽. Выглядит как ошибка
      // расчёта, но это требование НК: налог исчисляется в полных рублях.
      // Проверка 2026-08-17 по заявлению на 10 ₽ — на больших суммах
      // погрешность копеечная, на копеечных заметна.
      expect(calcNdflTax(10)).toBe(1);
      expect(calcNdflNet(10)).toBe(9);
    });

    it('налог всегда целое число рублей', () => {
      for (const gross of [1, 33, 99.99, 1234.56, 88888.88]) {
        expect(Number.isInteger(calcNdflTax(gross))).toBe(true);
      }
    });
  });

  describe('границы', () => {
    it('ноль и отрицательные суммы налога не дают', () => {
      expect(calcNdflTax(0)).toBe(0);
      expect(calcNdflTax(-100)).toBe(0);
    });

    it('нечисловое значение не роняет расчёт', () => {
      expect(calcNdflTax(Number.NaN)).toBe(0);
      expect(calcNdflTax(Number.POSITIVE_INFINITY)).toBe(0);
    });

    it('с копеечной суммы налог округляется в ноль, но выплата остаётся', () => {
      // 3 ₽ × 13 % = 0,39 → 0: удерживать нечего, получатель получает всё.
      expect(calcNdflTax(3)).toBe(0);
      expect(calcNdflNet(3)).toBe(3);
    });

    it('учитывает точность символа кооператива', () => {
      // Тот же результат при двухзначной точности — округление идёт до рубля,
      // а не до минорной единицы.
      expect(calcNdflTax(10000, 2)).toBe(1300);
      expect(calcNdflTax(107, 2)).toBe(14);
    });
  });
});
