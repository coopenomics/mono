/**
 * Удержание НДФЛ с материальной помощи доверенному кооперативного участка.
 *
 * Зеркало `BranchNdfl` из контракта
 * (`contracts/cpp/lib/core/branch/ndfl.hpp`) — source of truth там. Здесь
 * расчёт нужен, чтобы показать пайщику разбивку до подписания заявления и
 * выставить кассиру платёж ровно на ту сумму, которую потом спишет контракт.
 * Разойтись эти два расчёта не должны: кассир увидит одно, а цепь проведёт
 * другое — и платёж повиснет.
 *
 * Канон удержания (решение владельца 2026-08-13, отменяет requirement b6
 * п. 9 «налог платит получатель сам»):
 *
 *  - считаем от суммы заявления: заявление на 10 000 ₽ означает, что с
 *    персонального кошелька спишется 10 000 ₽, получателю уйдёт 8 700 ₽,
 *    а 1 300 ₽ станут долгом кооператива перед бюджетом;
 *  - ставка 13 %, фиксированная;
 *  - вычеты не применяются — получатель не работник кооператива, поэтому
 *    освобождение первых 4 000 ₽ материальной помощи к нему не относится;
 *  - налог исчисляется в полных рублях (п. 6 ст. 52 НК РФ): менее 50 копеек
 *    отбрасывается, 50 и более округляется до рубля.
 */

/** Ставка налога на доходы физических лиц, процентов. */
export const NDFL_RATE_PERCENT = 13;

/**
 * Сумма налога, удерживаемая из материальной помощи, в рублях.
 * Всегда целое число рублей — так же, как считает контракт.
 *
 * Считаем через минорные единицы, а не по дробным рублям: контракт работает
 * с целыми `asset.amount`, и повторять его арифметику надёжнее, чем полагаться
 * на double там, где половина рубля решает, округлить вверх или вниз.
 *
 * @param gross    сумма заявления в рублях
 * @param decimals точность символа кооператива (по умолчанию 4)
 */
export function calcNdflTax(gross: number, decimals = 4): number {
  if (!Number.isFinite(gross) || gross <= 0) return 0;
  const rouble = 10 ** decimals;
  const minor = Math.round(gross * rouble);
  const denominator = 100 * rouble;
  return Math.floor((minor * NDFL_RATE_PERCENT + denominator / 2) / denominator);
}

/**
 * Сумма к перечислению получателю — заявление за вычетом налога.
 * Именно она уходит кассиру в платёж и списывается операцией `o.brn.aid`.
 */
export function calcNdflNet(gross: number, decimals = 4): number {
  return gross - calcNdflTax(gross, decimals);
}

/** Разбивка выплаты для интерфейса: начислено / удержано / к перечислению. */
export interface NdflBreakdown {
  /** Сумма заявления — списывается с персонального кошелька целиком. */
  gross: number;
  /** Удержанный налог — остаётся долгом кооператива перед бюджетом. */
  tax: number;
  /** Сумма на счёт получателя. */
  net: number;
}

export function ndflBreakdown(gross: number, decimals = 4): NdflBreakdown {
  const tax = calcNdflTax(gross, decimals);
  return { gross, tax, net: gross - tax };
}
