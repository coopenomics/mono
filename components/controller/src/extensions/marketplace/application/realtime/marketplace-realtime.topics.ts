/**
 * Имя PubSub-топика персонального канала событий пайщика.
 *
 * Инвариант приватности: события публикуются и читаются ТОЛЬКО по топику
 * конкретного получателя. Подписчик строит топик из имени аккаунта своего
 * JWT (не из аргументов запроса), издатель (bridge) — из аккаунта-адресата
 * доменного события. Поэтому событие физически не попадает в канал чужого
 * пайщика. См. OQ-T15 (per-cooperative scope) — здесь усилено до per-member.
 */
export function marketplaceMemberTopic(coopname: string, username: string): string {
  return `marketplace:events:${coopname}:${username}`;
}

/**
 * Имя PubSub-топика широковещательного канала каталога кооператива.
 *
 * В отличие от персонального топика — общий для всех подписчиков кооператива:
 * появление нового предложения и изменение остатка должны быть видны всем
 * сразу, без перехода по страницам. Приватности здесь нет: каталог и так
 * публичен внутри кооператива (любой пайщик видит витрину). Payload —
 * по-прежнему только сигнал (идентификаторы), детали клиент дочитывает query.
 */
export function marketplaceCatalogTopic(coopname: string): string {
  return `marketplace:catalog:${coopname}`;
}

/**
 * Имя PubSub-топика служебного канала персонала кооперативных участков.
 *
 * Третий класс адресации — между персональным и широковещательным: оператор
 * у стойки (председатель КУ или доверенное лицо) не является стороной заказа,
 * но не может отпустить заказчика/поставщика, пока не увидит, что подпись
 * проставлена. Подключается ТОЛЬКО соединениям, чей аккаунт подтверждён как
 * персонал хотя бы одного КУ (trustee/trusted) — резолвер проверяет при
 * открытии подписки; рядовой пайщик этот канал не получает.
 */
export function marketplaceStaffTopic(coopname: string): string {
  return `marketplace:staff:${coopname}`;
}

/**
 * Имя PubSub-топика канала модерации предложений.
 *
 * Отдельный от служебного канала персонала КУ: модерирует председатель
 * кооператива (marketplace-роль admin = core-роль chairman), а не персонал
 * участка. Подключается ТОЛЬКО соединениям с ролью chairman — резолвер
 * проверяет при открытии подписки; клиент топики не выбирает.
 */
export function marketplaceModerationTopic(coopname: string): string {
  return `marketplace:moderation:${coopname}`;
}

/**
 * Имя PubSub-топика канала совета кооператива.
 *
 * Повестка списаний и надзорные столы совета: события проектов списания
 * адресуются членам совета и председателю (core-роли member/chairman), а не
 * персоналу КУ. Подключается ТОЛЬКО соединениям с этими ролями — резолвер
 * проверяет при открытии подписки; клиент топики не выбирает.
 */
export function marketplaceBoardTopic(coopname: string): string {
  return `marketplace:board:${coopname}`;
}
