/**
 * Порты контура, которые запрашивает расширение «Стол бухгалтера».
 *
 * Это его capability-заявка (ADR-16): что расширению вообще позволено просить
 * у кооператива. Права пайщика тут ни при чём — они проверяются на границе API
 * самого расширения; здесь речь о другом вопросе: какие данные и действия
 * контура доступны этому расширению как таковому.
 *
 * Обязательные порты проверяются при запуске расширения: отсутствие любого —
 * отказ с внятной причиной, а не молчаливое падение на первом вызове.
 * Необязательные могут отсутствовать: без них часть возможностей выключена.
 */
import {
  ACCOUNT_PORT,
  INDIVIDUAL_PORT,
  LEDGER2_HISTORY_PORT,
  ORGANIZATION_PORT,
  WITHHELD_TAX_PORT,
} from '@coopenomics/innercoop';

export const reportsPorts = {
  required: [
    ACCOUNT_PORT,
    // Справка о доходах (приложение № 1 к 6-НДФЛ) заполняется паспортом и
    // датой рождения получателя выплаты — без карточки физлица её не собрать.
    INDIVIDUAL_PORT,
    LEDGER2_HISTORY_PORT,
    ORGANIZATION_PORT,
  ],
  optional: [
    // Удержанный налог ведёт то расширение, которое выплачивает доход
    // физлицу. Его может не быть в кооперативе — тогда удерживать нечего, и
    // раздел перечислений пуст.
    WITHHELD_TAX_PORT,
  ],
};
