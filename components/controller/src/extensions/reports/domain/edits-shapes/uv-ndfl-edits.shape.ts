import type {
  ZeroReportHeaderShape,
  ZeroReportOrganizationShape,
  ZeroReportSignerShape,
} from './zero-report-edits.shape';

/**
 * Уведомление об исчисленных суммах НДФЛ — КНД 1110355, та же форма, на
 * которой уже сделаны уведомления по УСН и страховым взносам. Отличается от
 * них тремя вещами: своим КБК, периодичностью (дважды в месяц вместо раза) и
 * тем, что сумма не нулевая — она берётся из удержаний с материальной помощи.
 *
 * Это не часть 6-НДФЛ и не его раздел. 6-НДФЛ (КНД 1151100) — расчёт по
 * итогам квартала; уведомление говорит налоговой, сколько списать с единого
 * счёта, пока расчёт ещё не сдан. Совпадать они обязаны: сумма уведомления за
 * период — это одна из шести строк раздела 1 формы 6-НДФЛ.
 */

/** КБК НДФЛ по ставке 13 % — тот же, что в 6-НДФЛ. */
export const UV_NDFL_KBK = '18210102010011000110';

export interface UvNdflPaymentShape {
  /**
   * Сумма налога к перечислению за расчётный период, целые рубли.
   * Ноль означает, что удержаний в периоде не было и подавать нечего.
   */
  amount: number;
}

export interface UvNdflEditsShape {
  /**
   * `header.period` — сквозной номер расчётного периода 1..24: на каждый месяц
   * приходится два (с 1 по 22 число и с 23 по последнее). Хранить только номер
   * месяца нельзя — два уведомления за один месяц делили бы один черновик.
   */
  header: ZeroReportHeaderShape;
  organization: ZeroReportOrganizationShape;
  signer: ZeroReportSignerShape;
  payment: UvNdflPaymentShape;
}
