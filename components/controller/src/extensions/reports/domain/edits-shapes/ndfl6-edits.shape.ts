import type {
  ZeroReportHeaderShape,
  ZeroReportOrganizationShape,
  ZeroReportSignerShape,
} from './zero-report-edits.shape';

/**
 * 6-НДФЛ с реальными суммами. До 2026-08 форма была нулёвкой и делила
 * `ZeroReportEditsShape` с остальными: кооператив никому ничего не выплачивал
 * и налоговым агентом не был. С удержанием НДФЛ из материальной помощи
 * (процесс `p.brn.aid`) у формы появились собственные разделы, которых нет
 * ни у одной другой, — поэтому отдельный shape.
 *
 * Все суммы приходят посчитанными из ledger2, но остаются редактируемыми:
 * бухгалтер видит расчёт в форме и правит его, если у кооператива были
 * выплаты мимо платформы. Ручная правка держится dirty-merge'ем, как и
 * везде: пересчёт затирает всё, кроме полей, которых человек касался.
 */

/** Ставка налога. Целое число — дробные ставки схема 5.05 не принимает. */
export const NDFL6_RATE = 13;

/** КБК НДФЛ по ставке 13 % (база до 2,4 млн ₽ в год). */
export const NDFL6_KBK = '18210102010011000110';

/**
 * Код вида дохода «материальная помощь» для лица, которое работником не
 * является (приказ ФНС от 10.09.2015 № ММВ-7-11/387@). Именно 2710, а не
 * 2760: код 2760 — для работников и бывших работников-пенсионеров, и только
 * к нему применяется вычет 503 на первые 4 000 ₽. Получатель матпомощи в
 * кооперативе — доверенное лицо участка, а не работник, поэтому облагается
 * вся сумма.
 */
export const NDFL6_INCOME_CODE = '2710';

/**
 * Раздел 1 «Сведения об обязательствах налогового агента» и раздел 2
 * «Расчёт исчисленных и удержанных сумм налога».
 *
 * Важно про периоды, иначе суммы разъедутся: `withheldTotal` и `incomeTotal` —
 * **нарастающим итогом с начала года** (строки 020 и 160), а `byTerm` — только
 * **последний квартал** отчётного периода (строки 021–026 и 161–166, на бланке
 * они идут под «в том числе»). Совпадают эти величины лишь в отчёте за
 * 1 квартал.
 */
export interface Ndfl6TaxShape {
  /** Количество физлиц, получивших доход с начала года (строка 110). */
  peopleCount: number;
  /** Сумма дохода до удержания, с начала года, рубли с копейками (120). */
  incomeTotal: number;
  /** Сумма вычетов с начала года (130). Без вычетов — 0. */
  deductionsTotal: number;
  /** Налоговая база с начала года (131) = доход минус вычеты. */
  taxBase: number;
  /** Налог исчисленный, с начала года, целые рубли (140). */
  taxCalculated: number;
  /** Налог удержанный, с начала года, целые рубли (160 и 020). */
  withheldTotal: number;
  /**
   * Шесть сроков перечисления последнего квартала, целые рубли: 1–22 и 23–конец
   * по каждому из трёх месяцев (021–026, они же 161–166).
   */
  byTerm: [number, number, number, number, number, number];
}

/** Строка помесячного дохода в приложении к справке (код дохода + сумма). */
export interface Ndfl6MonthlyIncomeShape {
  /** Порядковый номер месяца 1..12. */
  month: number;
  /** Код вида дохода, 4 знака. */
  incomeCode: string;
  /** Сумма дохода за месяц по этому коду, рубли с копейками. */
  amount: number;
}

/**
 * Справка о доходах и суммах налога физического лица — приложение № 1,
 * по одной на каждого получателя. Сдаётся только в годовом отчёте: схема
 * запрещает справки при периодах 21/31/33.
 *
 * ИНН физлица здесь нет намеренно. Порядок заполнения (п. 32.1): «при
 * отсутствии у налогового агента информации об ИНН физического лица —
 * получателя дохода поле не заполняется», и `ПолучДох/@ИННФЛ` — единственный
 * необязательный реквизит получателя. Собирать ИНН с пайщиков не требуется.
 */
export interface Ndfl6CertificateShape {
  /** Имя аккаунта получателя — связка со справкой, в XML не попадает. */
  username: string;
  /** Порядковый номер справки в отчёте. */
  number: number;
  /** Номер корректировки, ровно две цифры: «00» первичная, «99» аннулирующая. */
  correctionNumber: string;
  lastName: string;
  firstName: string;
  middleName: string | null;
  /** Дата рождения в формате ДД.ММ.ГГГГ. */
  birthDate: string;
  /** Код статуса налогоплательщика: 1 — налоговый резидент РФ. */
  taxpayerStatus: string;
  /** Гражданство, числовой код страны по ОКСМ: 643 — Россия. */
  citizenshipCode: string;
  /** Код вида документа, удостоверяющего личность: 21 — паспорт РФ. */
  documentTypeCode: string;
  /** Серия и номер документа одной строкой — схема их не разделяет. */
  documentSerialNumber: string;
  /** Общая сумма дохода за год, рубли с копейками. */
  incomeTotal: number;
  /** Налоговая база за год, рубли с копейками. */
  taxBase: number;
  /** Налог исчисленный за год, целые рубли. */
  taxCalculated: number;
  /** Налог удержанный за год, целые рубли. */
  taxWithheld: number;
  /** Разбивка дохода по месяцам — приложение к справке. */
  monthlyIncome: Ndfl6MonthlyIncomeShape[];
}

export interface Ndfl6EditsShape {
  header: ZeroReportHeaderShape;
  organization: ZeroReportOrganizationShape;
  signer: ZeroReportSignerShape;
  tax: Ndfl6TaxShape;
  /**
   * Справки о доходах. Заполняются только для годового отчёта; в квартальных
   * массив пуст, и генератор их не выводит.
   */
  certificates: Ndfl6CertificateShape[];
}
