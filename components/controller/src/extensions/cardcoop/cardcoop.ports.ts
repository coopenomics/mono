/**
 * Порты контура, которые запрашивает расширение «Карта кооператора».
 *
 * Это его capability-заявка (ADR-16): что расширению вообще позволено просить
 * у кооператива. Обязательные проверяются при запуске — отсутствие любого даёт
 * отказ с внятной причиной, а не падение на первом вызове.
 *
 * Почему именно эти:
 * - `ACCOUNT_PORT` — тип субъекта пайщика (физлицо, ИП, организация) и признак
 *   членства: без него нечего подтверждать и неизвестно, какую карточку читать;
 * - `INDIVIDUAL_PORT` / `ORGANIZATION_PORT` — анкетные данные, из которых
 *   считается блок `identity` подтверждения (story 7.7): ФИО открыто, прочие
 *   поля — пополевыми отпечатками;
 * - `COOP_CREDENTIAL_PORT` — подпись ключом заверения и цепочка признания:
 *   подтверждение членства проверяется третьей стороной по признанному ключу
 *   кооператива, а сам ключ расширению не выдаётся — порт подписывает у себя;
 * - `USER_DIRECTORY_PORT` — по учётной записи из уведомления о связи находится
 *   пайщик: сеть присылает идентификатор записи в CoopID кооператива, а не имя;
 * - `LOGGER_PORT` — диагностика отправки и отзыва;
 * - `CHAIN_PORT` — наименование кооператива из записи цепи при объявлении допуска
 *   оператором (story 7.6): объявляется то, под чем кооператив зарегистрирован в цепи;
 * - `INTEGRATION_SETTINGS_PORT` — реквизиты клиента card.coop в CoopID установки: они
 *   задаются развёртыванием и доносятся в реестр сети подписанным документом (story 7.6),
 *   через настройки расширения не проходят;
 * - `VAULT_PORT` — подпись публикации ключа уведомлений сети в цепи (задача 3B5-51):
 *   установка оператора распоряжается аккаунтом `ano` по делегированным правам и сверяет
 *   ключ с цепью на каждом старте, а ключ подписи лежит в хранилище кооператива.
 */
import {
  ACCOUNT_PORT,
  CHAIN_PORT,
  COOP_CREDENTIAL_PORT,
  INDIVIDUAL_PORT,
  INTEGRATION_SETTINGS_PORT,
  LOGGER_PORT,
  ORGANIZATION_PORT,
  USER_DIRECTORY_PORT,
  VAULT_PORT,
} from '@coopenomics/innercoop';

export const cardcoopPorts = {
  required: [
    ACCOUNT_PORT,
    CHAIN_PORT,
    COOP_CREDENTIAL_PORT,
    INDIVIDUAL_PORT,
    INTEGRATION_SETTINGS_PORT,
    LOGGER_PORT,
    ORGANIZATION_PORT,
    USER_DIRECTORY_PORT,
    VAULT_PORT,
  ],
  optional: [],
};
