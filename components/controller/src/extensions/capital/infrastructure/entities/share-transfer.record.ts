export const ShareTransferEntityName = 'capital_share_transfers';

/**
 * Трансляция паевого взноса пайщика из Благороста в Цифровой Кошелёк:
 * сумма, подписанное заявление (1090) и транзакция цепи. Деньги двигает
 * контракт (`capital::wthshare`), заявление лежит в реестре документов цепи;
 * здесь — история трансляций для страницы трансляции. Запись резервируется
 * до отправки в цепь (повтор заявления упирается в уникальный индекс) и
 * подтверждается после ответа цепи; отказ цепи снимает резерв.
 */
export class ShareTransferRecord {
  _id!: string;

  coopname!: string;

  username!: string;

  /** Сумма в виде цепи: «1500.0000 RUB». */
  amount!: string;

  /** Хэш заявления — он же хэш процесса трансляции в реестре процессов. */
  statement_hash!: string;

  /** Подписанное заявление о трансляции паевого взноса (1090). */
  statement!: Record<string, unknown>;

  /** Транзакция `capital::wthshare`; пусто, пока цепь не ответила. */
  transaction_id!: string;

  /** Цепь приняла транзакцию. Неподтверждённая строка — резерв на время отправки. */
  confirmed!: boolean;

  created_at!: Date;
}
