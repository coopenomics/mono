/**
 * Форма имущества паевого взноса в «Благорост». Значение хранится строкой в
 * мете подписанного заявления, поэтому в GraphQL поле строковое, а не
 * перечисление: перечисление передавало бы ключи и меняло подписанную мету.
 */
export enum ProgramPropertyForm {
  THING = 'thing', // Вещь — имущество в натуральной форме
  INTANGIBLE = 'intangible', // Нематериальное имущество: документ, методика, файл
}
