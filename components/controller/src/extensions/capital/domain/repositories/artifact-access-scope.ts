/**
 * Ограничение выборки артефактов (проектов, задач, требований) правами пользователя.
 *
 * Передаётся в репозиторий вместе с фильтром, чтобы отсев шёл в SQL: иначе постраничные
 * `totalCount` и `totalPages` считаются по недоступным строкам и страницы приходят рваными.
 * `undefined` вместо области означает «ограничения нет» (председатель, член совета).
 */
export interface ArtifactAccessScope {
  /** Хеши проектов и компонентов, артефакты которых доступны пользователю. Пустой — не доступно ничего. */
  readonly projectHashes: readonly string[];
  /** Имя пользователя — для свободных задач, не привязанных ни к какому проекту. */
  readonly username?: string;
}
