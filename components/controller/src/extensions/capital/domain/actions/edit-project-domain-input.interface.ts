/**
 * Доменный интерфейс для действия редактирования проекта CAPITAL контракта
 */
export interface EditProjectDomainInput {
  /** Имя аккаунта кооператива */
  coopname: string;

  /** Хэш проекта для редактирования */
  project_hash: string;

  /** Новое название проекта */
  title: string;

  /** Новое описание проекта */
  description: string;

  /** Новое приглашение к проекту */
  invite: string;

  /** Новые мета-данные проекта */
  meta: string;

  /** Новые данные/шаблон проекта */
  data: string;
  /** Редакция содержимого, с которой начата правка (серверное слияние); без поля — запись без проверки. */
  base_rev?: number;
  /** Источник правки для истории редакций. */
  origin?: string;
  /** Для отката: номер редакции, к которой возвращаемся. */
  restored_from_rev?: number;

}
