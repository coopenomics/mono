/**
 * Заявка приложения каталога на порты ядра: что пакету разрешено и по какому
 * токену ядро его узнаёт. Сам токен не хранится — только его sha256.
 */
export class AppPortGrantRecord {
  /** Пакет каталога `@scope/name`. */
  packageId!: string;
  /** sha256 токена приложения, hex. */
  tokenHash!: string;
  /** Порты ядра, открытые приложению: имена из каталога удалённых портов. */
  ports!: string[];
  /** Действия цепи, которые ядро подпишет по просьбе приложения: `контракт::действие`. */
  chainActions!: string[];
  createdAt!: Date;
  updatedAt!: Date;
}
