/** Состояние приложения каталога на узле: переключатель и настройки. */
export class CatalogAppRecord {
  /** Пакет каталога `@scope/name`. */
  packageId!: string;

  /** Выключенное приложение не грузится на рабочий стол, подписка при этом идёт. */
  enabled!: boolean;

  /** Настройки приложения; схемы у пакетов каталога пока нет, поле держится под неё. */
  config!: Record<string, unknown>;

  updatedAt!: Date;
}
