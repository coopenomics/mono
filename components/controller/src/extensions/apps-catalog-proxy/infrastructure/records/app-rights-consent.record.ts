/**
 * Согласие председателя на права ядра приложения каталога (487-37): что
 * приложению разрешено и какой запрос новых прав ждёт ответа. Ключ приложению
 * ядро выдаёт только в пределах согласия.
 */
export class AppRightsConsentRecord {
  /** Пакет каталога `@scope/name`. */
  packageId!: string;
  /** Порты ядра, с которыми председатель согласился. */
  ports!: string[];
  /** Действия цепи `контракт::действие`, с которыми председатель согласился. */
  chainActions!: string[];
  /** Принимать новые права без вопроса, после одобрения модератора каталога. */
  autoAccept!: boolean;
  /** Кто дал согласие: имя аккаунта, `auto` — переключатель, `migration` — перенос установленных до правила. */
  consentedBy!: string | null;
  consentedAt!: Date | null;
  /** Порты, которые новая версия просит сверх согласия. */
  pendingPorts!: string[];
  /** Действия цепи, которые новая версия просит сверх согласия. */
  pendingChainActions!: string[];
  /** Версия, которая ждёт согласия; `null` — запроса нет. */
  pendingVersion!: string | null;
  pendingAt!: Date | null;
  createdAt!: Date;
  updatedAt!: Date;
}
