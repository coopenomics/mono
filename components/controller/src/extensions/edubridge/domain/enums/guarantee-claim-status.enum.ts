/** Ход заявления об аннулировании подписки по гарантийным условиям. */
export enum EduGuaranteeClaimStatus {
  /** Заявление подано и вынесено на совет. */
  SUBMITTED = 'submitted',
  /** Совет удовлетворил: подписка аннулирована, стоимость возвращена на паевой. */
  APPROVED = 'approved',
  /** Совет отклонил вопрос: у участника остаётся обычный отказ от подписки. */
  DECLINED = 'declined',
  /** Совет не принял решение в срок. */
  EXPIRED = 'expired',
}
