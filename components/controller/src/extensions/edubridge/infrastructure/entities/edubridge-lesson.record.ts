
/**
 * Занятие группы: календарь и журнал в одной записи. Занятие появляется из
 * окон расписания либо назначается администратором отдельно, живёт в
 * календаре как запланированное, а отчёт преподавателя после занятия переводит
 * его в проведённое: материалами работа овеществляется, и по отчёту контракт
 * считает взнос преподавателя. Номер занятия — место в программе курса, он
 * стабилен: перенос даты номер не меняет, отмена номер освобождает.
 */
import { EduLessonOrigin, EduLessonStatus } from '../../domain/enums';

export class EdubridgeLessonRecord {
  public id!: string;

  public coopname!: string;

  /** Преподаватель занятия; `null` — в календаре преподаватель ещё не назначен. */
  public teacher_username!: string | null;

  public course_id!: string;

  /** Группа курса, для которой проведено занятие. */
  public group_id!: string | null;

  /** Допуск преподавателя, по которому идёт расчёт; `null` — преподаватель ещё не назначен. */
  public assignment_id!: string | null;

  /** Номер занятия в программе курса — от единицы до числа занятий курса. */
  public lesson_number!: number;

  /** Момент занятия: из календаря; у проведённого занятия — когда проведено. */
  public held_at!: Date;

  /** Запланировано, проведено либо отменено. */
  public status!: EduLessonStatus;

  /** Из окон расписания либо назначено отдельно. */
  public origin!: EduLessonOrigin;

  /** Когда преподаватель отчитался; `null` — отчёта нет. */
  public reported_at!: Date | null;

  /** Длительность занятия, минут: по умолчанию — из расписания курса. */
  public duration_minutes!: number;

  /** Материалы занятия: записи, конспекты, задания — ссылки на внешние хранилища. */
  public materials!: string[];

  public topic!: string;

  /** Взнос, оформленный по этому занятию; null — отчёт без взноса. */
  public contribution_id!: string | null;

  /** Участников с оплаченным доступом, по которым контракт провёл расчёт за занятие; `null` — расчёт не проводился. */
  public learners_count!: number | null;

  public created_at!: Date;
}
