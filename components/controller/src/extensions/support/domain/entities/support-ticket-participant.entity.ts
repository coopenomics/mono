/**
 * Член совета, подключённый к обращению помимо назначенного ответственного.
 *
 * **Это подписка, а не право.** Совет и так читает любое обращение кооператива
 * и пишет в любое — участие ничего не открывает и ничего не закрывает. Нужно
 * оно для двух вещей: адресовать уведомление и отобрать обращения в очереди
 * («где я участвую»). Если где-то появится проверка вида «участник ли он» в
 * роли проверки права — это ошибка, а не развитие модели.
 *
 * **Ответственный участником не становится.** `assigneeUsername` остаётся
 * отдельной колонкой обращения и сюда не дублируется: дублирование завело бы
 * инвариант «ответственный обязан быть в списке участников», проверять который
 * некому и который рано или поздно разойдётся с действительностью. Ответная
 * сторона обращения — объединение одного с другим, а не одно из двух.
 *
 * **Собственный идентификатор нужен не только базе.** Он служит различителем
 * в ключе подавления повторов у уведомления о подключении: отключили и
 * подключили снова — это новая запись с новым идентификатором, а значит второе
 * письмо дойдёт. Пара «обращение и человек» в этой роли не годится — она у
 * повторного подключения та же самая.
 */
export interface SupportTicketParticipantDomainEntity {
  id: string;
  ticketId: string;
  /** Кого подключили. Всегда член совета — проверяется при подключении. */
  participantUsername: string;
  /** Кто подключил. Нужен, чтобы не слать письмо подключившему самого себя. */
  addedByUsername: string;
  addedAt: Date;
}
