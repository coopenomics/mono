/**
 * Общее для команд и чтений: кто считается советом и что отвечать на закрытое.
 *
 * Обе величины появились в слое команд, а теперь нужны и слою чтений. Копия
 * здесь была бы худшим из возможных дублей: разойдись список ролей или текст
 * ответа — и одна половина стола начала бы отвечать иначе, чем другая, причём
 * молча.
 */

/** Роли, составляющие совет. Оператор в первой версии — это член совета. */
export const COUNCIL_ROLES: ReadonlyArray<string> = ['chairman', 'member'];

/**
 * Ответ пайщику и про несуществующее обращение, и про чужое.
 *
 * Текст один на оба случая намеренно: если чужое обращение отвечает «нет
 * прав», а несуществующее — «не найдено», разница ответов сама по себе
 * сообщает, что обращение с таким идентификатором существует. Перебором это
 * превращается в список чужих обращений, ничего не показывая напрямую.
 */
export const TICKET_NOT_FOUND_MESSAGE = 'Обращение не найдено.';

/** Входит ли актор в совет кооператива. */
export function isCouncilRole(role: string): boolean {
  return COUNCIL_ROLES.includes(role);
}
