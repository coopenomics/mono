import { SupportTicketStatus } from '../domain/enums/support-ticket-status.enum';

/**
 * Порог автозакрытия — единственный источник величины.
 *
 * Значение нужно двоим: фоновой задаче, которая закрывает обращения, и
 * расчётному полю «когда закроется» в карточке. Два источника одной величины
 * неизбежно разъедутся, и тогда пайщику будет показано одно время, а закроется
 * обращение в другое — причём расхождение не поймает ни компилятор, ни тест,
 * который смотрит на одну сторону.
 *
 * Значение из переменной окружения: порог задаёт кооператив, а не сборка. По
 * умолчанию 48 часов — верхняя граница согласованного окна 24–48. Смысл
 * ожидания в том, чтобы пайщик успел возразить, и меньшее значение урезает эту
 * гарантию без нужды. Подтверждено председателем 18.08.2026.
 */
export const SUPPORT_AUTO_CLOSE_HOURS = Number(process.env.SUPPORT_AUTO_CLOSE_HOURS) || 48;

const HOUR_MS = 60 * 60 * 1000;

/**
 * Когда обращение закроется само.
 *
 * Вычисляется, а не хранится: при изменении порога все хранимые значения
 * разъехались бы с поведением таймера (спецификация, раздел 4).
 *
 * `null` означает «отсчёт не идёт», и таких случаев два. Обращение не помечено
 * решённым (либо возвращено в работу — тогда отсчёт обнулён). И обращение уже
 * закрыто: `resolved_at` у него заполнен и никуда не делся, поэтому одного
 * отсчёта мало — по нему карточка закрытого обращения показала бы «закроется
 * автоматически» с датой в прошлом. Отсюда проверка статуса.
 */
export function supportAutoCloseAt(
  status: SupportTicketStatus,
  resolvedAt: Date | null
): Date | null {
  if (status !== SupportTicketStatus.RESOLVED || !resolvedAt) return null;
  return new Date(resolvedAt.getTime() + SUPPORT_AUTO_CLOSE_HOURS * HOUR_MS);
}
