/**
 * Права пайщика на столах поддержки.
 *
 * Вид «Ресурс:действие» — канон авторизации столов платформы: маршрут
 * объявляет требование в `meta.requires`, провайдер выдаёт набор, интерфейс
 * сверяет одно с другим. Собственной политики у интерфейса нет.
 *
 * **Права прячут, отказывает сервер.** Настоящая проверка стоит на резолверах;
 * эти две строки решают только, покажется ли стол в переключателе и пункт в
 * меню. Третьего места с теми же правилами быть не должно.
 */

/**
 * Подать обращение и вести своё — стол пайщика.
 *
 * Право выдаётся любому пайщику кооператива, и это не формальность: страница
 * без требования в грант-управляемом столе **скрыта** (`isPageVisible` в
 * `DesktopStore` считает отсутствие требования отказом, иначе пустой набор
 * прав открыл бы страницу всем подряд). Стол поддержки становится
 * грант-управляемым из-за стола совета — провайдер прав один на расширение и
 * прикрепляется ко всем его столам сразу. Поэтому «требования нет» здесь
 * означало бы «стол пайщика не видно никому», а не «доступно всем».
 */
export const SUPPORT_TICKET_CREATE_GRANT = 'SupportTicket:create';

/** Вести очередь обращений кооператива — стол совета. */
export const SUPPORT_TICKET_OPERATE_GRANT = 'SupportTicket:operate';
