/**
 * События стола поддержки для Центра уведомлений.
 *
 * Их три — по числу согласованных уведомлений. Два первых из спецификации
 * (раздел 7), третье добавлено решением председателя от 20.08.2026 вместе с
 * участниками обращения. Все излучаются в прикладном сервисе ПОСЛЕ фиксации
 * транзакции: не в репозитории и не в резолвере. Из транзакции уведомления не
 * отправляют вообще, порядок всегда «запись в базу → событие → слушатель зовёт
 * порт вне транзакции».
 *
 * Именование — домен, сущность, адресат, событие (канон marketplace). Адресат
 * в имени не украшение: у двух первых событий это `author`, у третьего —
 * `participant`, и оно единственное на столе, что уходит не автору обращения.
 *
 * Адресат в самом событии не вычисляется: событие — это факт домена, и он
 * произошёл независимо от того, кому о нём писать. Слушатель определяет
 * получателя и гасит отправку, когда инициатор совпадает с получателем: ни
 * пайщик о собственном сообщении, ни член совета о собственном подключении
 * письма не получают.
 *
 * Отметок текущего времени в составе нет намеренно: ключ подавления повторов
 * в очереди уведомлений считается в том числе от данных шаблона, и время
 * внутри payload'а превратило бы одно событие в два разных письма.
 *
 * Зато в составе есть различитель — идентификатор той записи, из-за которой
 * событие произошло: `message_id` у двух первых, `participation_id` у
 * третьего. Он закрывает обратную опасность, о которой спецификация умалчивает:
 * ключ подавления повторов считается от данных шаблона, поэтому два разных
 * ответа на одно обращение дали бы одинаковый ключ (номер, тема и ссылка у них
 * те же) — и второе письмо молча не ушло бы. Идентификатор записи различает
 * события, оставаясь неизменным у одного и того же: повтор после сбоя доставки
 * по-прежнему безопасен.
 */
import { SupportMessageAuthorRole } from '../../domain/enums/support-message-author-role.enum';
import { SupportTicketStatus } from '../../domain/enums/support-ticket-status.enum';

/** В обращение добавлено человеческое сообщение (системные записи событие не излучают). */
export const SUPPORT_TICKET_AUTHOR_REPLIED_EVENT = 'support.ticket.author.replied';

/** Статус обращения изменился на один из переходов, видимых пайщику. */
export const SUPPORT_TICKET_AUTHOR_STATUS_CHANGED_EVENT = 'support.ticket.author.statusChanged';

/**
 * К обращению подключён участник — единственное событие стола, адресованное не
 * автору обращения, а члену совета. Отсюда и другой адресат в имени.
 */
export const SUPPORT_TICKET_PARTICIPANT_ADDED_EVENT = 'support.ticket.participant.added';

export interface SupportTicketAuthorRepliedEvent {
  coopname: string;
  ticket_id: string;
  /** Запись ленты, о которой уведомление. Различает события в ключе подавления повторов. */
  message_id: string;
  /** Человеко-читаемый номер обращения — им уведомление называет обращение. */
  ticket_number: string;
  subject: string;
  /** Автор сообщения. Слушателю нужен, чтобы не написать пайщику о его же реплике. */
  author_username: string;
  /** Роль автора снимком: по ней слушатель решает, от чьего лица пришёл ответ. */
  author_role: SupportMessageAuthorRole;
}

export interface SupportTicketAuthorStatusChangedEvent {
  coopname: string;
  ticket_id: string;
  /** Системная запись ленты о переходе. Различает события в ключе подавления повторов. */
  message_id: string;
  ticket_number: string;
  subject: string;
  previous_status: SupportTicketStatus;
  status: SupportTicketStatus;
  /**
   * Кто вызвал переход. У автозакрытия инициатора нет — поле пустое, и
   * уведомление в этом случае уходит всегда.
   */
  initiator_username: string | null;
}

export interface SupportTicketParticipantAddedEvent {
  coopname: string;
  ticket_id: string;
  /**
   * Запись подключения. В этом событии она играет ту же роль, что `message_id`
   * в двух других, — различает события в ключе подавления повторов. Пара
   * «обращение и участник» на эту роль не годится: у повторного подключения
   * того же человека она та же самая, и второе письмо молча не ушло бы.
   * Отключение удаляет запись физически, поэтому повторное подключение даёт
   * новый идентификатор и новый ключ.
   */
  participation_id: string;
  ticket_number: string;
  subject: string;
  /** Кого подключили — он же получатель уведомления. */
  participant_username: string;
  /** Кто подключил. Слушателю нужен, чтобы не написать подключившему самого себя. */
  initiator_username: string;
}
