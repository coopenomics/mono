/**
 * Кто выполняет операцию стола поддержки.
 *
 * Лежит отдельным файлом, а не рядом с входными данными команд: актор нужен
 * одинаково и командам, и чтениям, и слою видимости. Пока он жил в
 * `support-commands.types.ts`, три четверти его пользователей импортировали
 * «типы команд» ради того, что к командам не относится, — имя файла отстало от
 * содержимого ещё на фазе чтений.
 *
 * Передаётся явным параметром, а не берётся из глобального контекста запроса:
 * прикладной сервис не должен знать, что вызов вообще пришёл по HTTP.
 */
export interface SupportActor {
  username: string;
  /** Роль в кооперативе: `chairman`, `member`, `user`. */
  role: string;
}

/**
 * Учётная запись платформы → актор стола.
 *
 * Структурно передать `IMonoAccount` можно было бы и целиком — состав
 * совместим. Но тогда объявленная узость актора становится обещанием на
 * словах: внутрь прикладного слоя физически попадают почта, открытый ключ и
 * состояние регистрации, и первый же, кто ими воспользуется, не нарушит ни
 * одного типа. Явное сужение на границе возвращает объявлению силу.
 *
 * Параметр описан минимально, а не типом учётной записи: резолверу этого
 * достаточно, а слой перестаёт зависеть от формы платформенной записи.
 */
export function toSupportActor(account: { username: string; role: string }): SupportActor {
  return { username: account.username, role: account.role };
}
