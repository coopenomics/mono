/**
 * Роль документа в процессе — строка журнала документов (signed_documents).
 * Пакетный вид реестра показывает заявления, плоский — все роли.
 */
export enum SignedDocumentRole {
  /** Заявление — главный документ пакета процесса. */
  Statement = 'statement',
  /** Решение совета по заявлению. */
  Decision = 'decision',
  /** Акт процесса (приёма-передачи, выдачи). */
  Act = 'act',
  /** Связанный документ процесса (newlink). */
  Link = 'link',
  /** Соглашение, которое заявление перечисляет в своих связях (вступление). */
  Agreement = 'agreement',
}
