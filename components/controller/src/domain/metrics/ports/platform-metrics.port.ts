/**
 * Снимок прикладных показателей кооператива для экспозиции в Prometheus.
 *
 * Порт намеренно один и отдаёт всё одним вызовом: это телеметрия, а не рабочий
 * сценарий. Дробить её на четыре порта с четырьмя адаптерами значило бы завести
 * слой ради слоя — читается всё равно одна и та же база одним тиком.
 *
 * ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ.
 *
 * Числа строк в `blockchain_deltas` и `blockchain_actions` — это самые большие
 * таблицы узла, и `count(*)` по ним означает последовательное чтение всей
 * таблицы каждый тик. Отставание парсера показывают позиция чтения и возраст
 * курсора: они берутся из Redis и стоят ноль.
 *
 * Активность пайщиков — она не выводится из этой базы вовсе. Единственный след
 * входа здесь, таблица `tokens`, при сроке жизни токена в 600 суток даёт одну
 * строку на пайщика за всё время. Активность считает отдельный порт
 * {@link ../ports/user-activity.port.ts}, по факту заходов.
 */
export interface PlatformMetricsSnapshot {
  /** Пайщики по статусу учётной записи (`users.status`). */
  usersByStatus: Record<string, number>;
  /**
   * У скольких пайщиков ВЫСТАВЛЕН ФЛАГ `users.has_account`.
   *
   * Это не «сколько пайщиков имеют аккаунт в цепи», а состояние флага, который
   * ставит контроллер при создании аккаунта. Флаг расходится с реальностью:
   * 29.08.2026 на дев-стенде у пайщика `ant` он был false при непустом
   * `public_key` и живой строке в `soviet::participants`. Метрика оставлена
   * именно ради видимости этого расхождения — сравнение с двумя следующими
   * показывает, где учётные записи разъехались с цепью.
   */
  usersWithAccountFlag: number;
  /** У скольких пайщиков сохранён публичный ключ цепи (`users.public_key`). */
  usersWithChainKey: number;
  /**
   * Сколько пайщиков в реестре кооператива В САМОЙ ЦЕПИ — живые строки
   * `soviet::participants` из журнала дельт. Это авторитетный ответ на вопрос
   * «сколько у нас пайщиков»: он не зависит от того, что успел записать о себе
   * контроллер. Выборка идёт по индексу (code, table), полного чтения журнала
   * дельт нет.
   */
  chainParticipants: number;
  /** Кандидаты по статусу заявления (`candidates.status`). */
  candidatesByStatus: Record<string, number>;
  /** Глубина транзакционного outbox Центра уведомлений по статусу строки. */
  notificationOutboxByStatus: Record<string, number>;
}

export interface PlatformMetricsPort {
  collect(): Promise<PlatformMetricsSnapshot>;
}

export const PLATFORM_METRICS_PORT = Symbol('PlatformMetricsPort');
