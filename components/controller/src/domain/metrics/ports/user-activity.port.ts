/**
 * След захода пайщика — «был ли он в системе за сутки».
 *
 * Зачем отдельный порт, а не выборка из базы: следа заходов в схеме нет вовсе.
 * Таблица `tokens` показывает ВЫДАЧУ токена, то есть вход, а не работу: при
 * JWT_ACCESS_EXPIRATION_MINUTES=864000 (600 суток) и refresh на год пайщик,
 * заходящий в кабинет каждый день, оставляет там одну строку за всё время.
 * Считать по ней активность значит показывать дату регистрации.
 *
 * Реализация — счётчик уникальных значений (HyperLogLog) по суткам: он не
 * хранит сами имена и занимает фиксированные ~12 КБ на день независимо от
 * числа пайщиков. Плата за это — приближённость, но до нескольких сотен
 * значений счётчик хранит их точно и переходит в приближённый режим только
 * дальше, то есть на размерах кооператива ошибки нет.
 */
export interface UserActivityPort {
  /**
   * Отметить, что пайщик заходил. Вызывается на КАЖДОМ авторизованном запросе,
   * поэтому обязана быть дешёвой и молчаливой: сбой записи следа не имеет права
   * уронить сам запрос.
   */
  markActive(username: string): Promise<void>;

  /**
   * Сколько РАЗНЫХ пайщиков заходили за последние `days` суток, включая
   * сегодняшние. `days = 1` — сегодняшний день.
   */
  countActive(days: number): Promise<number>;
}

export const USER_ACTIVITY_PORT = Symbol('UserActivityPort');
