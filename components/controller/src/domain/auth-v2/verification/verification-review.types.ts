/**
 * Проверка сверки личности советом кооператива.
 *
 * Личность сверяет кооперативный участок: оператор смотрит паспорт и снимает
 * фотографии сверки. Уровень выдаётся сразу — иначе пайщик не заберёт заказ,
 * пока не проснётся совет. Снятое ложится в запись со статусом «на проверке»,
 * и председатель совета её утверждает либо отклоняет; отклонение отзывает
 * верификацию на цепи.
 *
 * Снимки — временные. Как только председатель решил, они удаляются: задача
 * узкая (убедиться, что пришёл тот, кто зарегистрирован), и хранить копии
 * чужих паспортов после её решения незачем. Остаётся только факт: кто сверил,
 * где, когда и кто утвердил.
 */

/** Состояние проверки. */
export enum VerificationReviewStatus {
  /** Участок сверил личность, совет ещё не проверил. Снимки на месте. */
  Pending = 'pending',
  /** Совет подтвердил сверку. Снимки удалены. */
  Approved = 'approved',
  /** Совет отклонил сверку — верификация отозвана с цепи. Снимки удалены. */
  Rejected = 'rejected',
  /** Верификация отозвана председателем после утверждения. */
  Revoked = 'revoked',
}

/** Один снимок сверки в хранилище кооператива. */
export interface VerificationReviewPhoto {
  storage_key: string;
  checksum_sha256: string;
  mime_type: string;
  size_bytes: number;
  original_filename?: string | null;
  uploaded_at: string;
}

/** Запись журнала верификаций: одна сверка личности со всей её судьбой. */
export interface VerificationReview {
  id: string;
  /** Пайщик, чью личность сверяли. */
  username: string;
  /** Процедура сверки (`passport`). */
  procedure: string;
  /** Участок, где сверяли; пусто — сверял совет кооператива. */
  braname: string;
  /** Кто сверил личность. */
  verificator: string;
  status: VerificationReviewStatus;
  /** Снимки сверки; пусто после решения совета. */
  photos: VerificationReviewPhoto[];
  created_at: string;
  /** Кто вынес решение (утвердил, отклонил, отозвал). */
  decided_by?: string | null;
  decided_at?: string | null;
  /** Причина отклонения или отзыва. */
  decision_reason?: string | null;
}
