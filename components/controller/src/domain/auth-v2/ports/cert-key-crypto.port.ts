import type { KeyObject } from 'node:crypto';

/**
 * Работа с ключом заверения удостоверений на уровне криптографии: выпуск, вывод
 * публичной части, приведение к виду, которым подписывают.
 *
 * Порт нужен ради гексагонального инварианта auth-v2: прикладной слой не знает ни
 * про библиотеку цепи, ни про форматы ключей — он оперирует строками и объектом
 * подписи, а всё преобразование живёт в инфраструктуре.
 */
export interface ICertKeyCrypto {
  /** Выпускает новый ключ заверения. Возвращает приватную часть в формате цепи. */
  generate(): string;

  /** Публичная часть ключа цепи (`PUB_K1_…`). */
  publicKeyOf(privateKey: string): string;

  /**
   * Публичная часть ключа, заданного секретом поставки (PEM). Форматы разные:
   * секрет заводят обычными криптографическими инструментами, а цепь знает свой.
   */
  publicKeyOfPem(pem: string): string;

  /** Ключ из секрета поставки (PEM) → формат цепи; дальше он ничем не отличается от выпущенного. */
  pemToChainKey(pem: string): string;

  /** Ключ цепи → объект подписи Node, которым подписывается удостоверение. */
  toSigningKey(privateKey: string): KeyObject;

  /**
   * Подписывает байты ключом цепи и возвращает подпись в формате цепи (`SIG_K1_…`).
   *
   * Отдельно от {@link toSigningKey}: тот отдаёт объект подписи Node, которым
   * удостоверение подписывается в формате JWS, а здесь нужна подпись в формате
   * самой цепи — её проверяют по признанному ключу из `ano::endorsements`.
   */
  signChainMessage(privateKey: string, message: Uint8Array): string;

  /** Приводит публичный ключ к единому виду — записи цепи бывают в двух форматах. */
  normalizePublicKey(publicKey: string): string;
}

export const CERT_KEY_CRYPTO_PORT = Symbol('CertKeyCryptoPort');
