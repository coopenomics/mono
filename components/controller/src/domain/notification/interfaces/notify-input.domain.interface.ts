/**
 * Канал доставки уведомления.
 *
 * Остальные типы входа уведомления переехали в `@coopenomics/innercoop`:
 * их контракт нужен расширениям, а этого пути за пределами монолита нет.
 * Здесь остался только перечень каналов — он часть реализации центра
 * уведомлений, а не контракта: расширение указывает тип уведомления, каналы
 * подбирает каталог.
 */
export enum NotificationChannel {
  EMAIL = 'email',
  IN_APP = 'in_app',
  PUSH = 'push',
}
