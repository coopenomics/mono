/**
 * Регистр в хэшах из цепи не значим, а на практике гуляет.
 *
 * Цепь отдаёт `checksum256` заглавными, но по дороге хэш успевает побывать
 * строчным: индексер кладёт в журнал то, что пришло в теле действия, фронт
 * присылает то, что показал пользователю, а сравниваются они потом как обычные
 * строки — и не совпадают. Точный поиск по такому полю молча возвращает
 * пустоту: вопрос не появляется в повестке, связанный документ не находится,
 * при этом ни ошибки, ни предупреждения нигде нет.
 *
 * Поэтому значение, которое выглядит как hex-хэш, сравнивается без учёта
 * регистра. Остальные поля полезной нагрузки (имена аккаунтов, суммы, тексты)
 * сравниваются как есть: там регистр может быть значимым.
 */
export function isHexHash(value: string): boolean {
  return /^[0-9a-fA-F]{32,64}$/.test(value);
}
