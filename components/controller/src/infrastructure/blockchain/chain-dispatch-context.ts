import { AsyncLocalStorage } from 'node:async_hooks';

/**
 * Признак «код выполняется внутри разбора событий цепи».
 *
 * Транзакция ждёт, пока узел разберёт блок, в который она попала
 * (`BlockchainService.transact`). Изнутри разбора так ждать нельзя: обработчик
 * дельты потребитель ждёт сам, и транзакция из обработчика ждала бы блок,
 * который потребитель не возьмёт, пока обработчик не закончит, — взаимная
 * блокировка до истечения обоих пределов. Отвечать такой транзакции некому:
 * её отправляет автоматика (робот совета, реакции на события), а не пайщик.
 */
const storage = new AsyncLocalStorage<true>();

/** Выполнить обработку события цепи с признаком разбора. */
export function runInChainDispatch<T>(fn: () => T): T {
  return storage.run(true, fn);
}

/** Вызов пришёл из разбора событий цепи — ждать разбора блока нельзя. */
export function isInChainDispatch(): boolean {
  return storage.getStore() === true;
}
