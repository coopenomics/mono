import { Entity, PrimaryGeneratedColumn, Column, CreateDateColumn, Index, Unique } from 'typeorm';

/**
 * Версия шаблона документа, как она выглядела на определённом блоке.
 *
 * Таблица устроена как история, а не как «текущее состояние»: каждая правка
 * шаблона в цепи добавляет строку со своим номером блока, старые остаются.
 * Иначе документ, подписанный год назад, при повторной сборке получил бы
 * сегодняшний текст — а его хэш и подписи относятся к прежнему.
 *
 * Читается всегда через «последняя версия с block_num не больше искомого».
 * Номер блока, на который смотреть, берётся из meta самого документа.
 */
@Entity('draft_templates')
@Unique(['registry_id', 'block_num'])
@Index(['registry_id', 'block_num'])
export class DraftTemplateEntity {
  @PrimaryGeneratedColumn('uuid')
  id!: string;

  /** Номер шаблона в реестре документов платформы. */
  @Column({ type: 'bigint' })
  registry_id!: string;

  /** Блок, на котором шаблон принял это состояние. */
  @Column({ type: 'bigint' })
  block_num!: number;

  /**
   * Строка таблицы `draft::drafts` целиком.
   *
   * Хранится как есть, без разбора на колонки: состав полей шаблона задаёт
   * контракт, и он меняется вместе с версиями контракта. Разложив его по
   * колонкам, мы бы обязались мигрировать таблицу при каждом таком изменении,
   * а читателю нужен ровно тот же объект, что приходил из обозревателя.
   */
  @Column({ type: 'jsonb' })
  value!: any;

  /**
   * false — строка удалена из он-чейн таблицы. Версия сохраняется: для
   * документов, подписанных до удаления, шаблон обязан остаться доступным.
   */
  @Column({ type: 'boolean', default: true })
  present!: boolean;

  @CreateDateColumn()
  created_at!: Date;
}
