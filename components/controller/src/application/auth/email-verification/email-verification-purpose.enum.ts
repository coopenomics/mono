/**
 * Зачем пайщику код подтверждения почты.
 *
 * От назначения зависит, можно ли слать код на адрес, у которого уже есть
 * учётная запись: в кабинете это и есть её владелец, а в регистрации — повод
 * сразу отправить человека ко входу, не заставляя искать письмо.
 */
export enum EmailVerificationPurpose {
  /** Первый шаг регистрации: учётной записи с этим адресом быть не должно. */
  Registration = 'registration',
  /** Подтверждение адреса из личного кабинета. */
  Account = 'account',
}
