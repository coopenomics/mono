/**
 * Права пайщика на рабочем столе расширения.
 *
 * Направление обратное портам ядра: контракт реализует расширение, а вызывает
 * ядро, когда собирает рабочий стол пайщика. Единый источник истины «кто что
 * видит» — сервер: интерфейс лишь сверяет требования страницы с выданным
 * набором, собственной проверки прав у него нет.
 *
 * Расширение без такого провайдера работает по-старому — набор не приходит
 * вовсе, и видимость определяется ролью. Контракт необязателен и ничего не
 * ломает у тех, кто его не реализует.
 */

/** Что известно о пайщике в момент вычисления прав. */
export interface InnerDesktopGrantsContext {
  coopname: string;
  /** Учётное имя; отсутствует у неавторизованного гостя. */
  username?: string;
  /** Роль в кооперативе: пайщик, член совета, председатель. */
  userRole?: string;
  /** Состояние членства — для прав, требующих активного пайщика. */
  userStatus?: string;
  /** Настройка расширения: по ней видно, принята ли программа кооперативом. */
  config?: Record<string, any>;
}

export interface IDesktopGrantsHook {
  /** Имя расширения в реестре платформы. */
  readonly extensionName: string;

  /**
   * Права текущего пайщика плоским списком.
   *
   * Разворачивать иерархию обязано само расширение: право «на всё» должно
   * превратиться в перечень частных прав, иначе интерфейсу пришлось бы
   * повторять у себя правила охвата — а он их не знает и знать не должен.
   * Гость и не-пайщик получают пустой список.
   */
  resolveGrants(context: InnerDesktopGrantsContext): Promise<string[]>;
}

/**
 * Реестр провайдеров прав. Расширение кладёт себя сюда при запуске, а собирает
 * рабочий стол ядро.
 */
export interface IDesktopGrantsRegistryPort {
  register(provider: IDesktopGrantsHook): void;
}

export const DESKTOP_GRANTS_REGISTRY_PORT = Symbol.for('Innercoop.CorePort.DesktopGrantsRegistry');
