/**
 * Удержанный налог, ожидающий перечисления в бюджет.
 *
 * Кооператив удерживает налог там, где выплачивает доход физлицу, — сегодня
 * это материальная помощь доверенным кооперативных участков (Стол заказов).
 * Перечисляет же его бухгалтерия: единым платежом за период, а не по каждой
 * выплате. Порт и разделяет эти две стороны — расширение-источник ведёт
 * удержания и заявки на цепи, стол бухгалтера показывает долг и отправляет
 * его на оплату.
 *
 * Без источника удержаний (расширение не установлено) порт отсутствует, и
 * стол бухгалтера обязан это пережить: удержаний нет — платить нечего.
 */

/** Сколько удержано и что из этого уже в пути к кассиру. */
export interface InnerWithheldTaxState {
  /** Удержано и ещё не перечислено — долг перед бюджетом целиком. */
  withheld: string;
  /** Отправлено на оплату и ждёт подтверждения кассиром. */
  in_payment: string;
  /** Доступно к отправке: удержано за вычетом того, что уже у кассира. */
  available: string;
}

/**
 * Отправленный на оплату налог — одна заявка бухгалтера кассиру.
 *
 * Состояние берётся у платежа кассирского стола, поэтому здесь те же значения,
 * что и в реестре платежей: ждёт кассира, оплачен, отклонён.
 */
export interface InnerWithheldTaxPayment {
  /** Хэш заявки: он же связывает платёж с записью на цепи. */
  hash: string;
  /** Сумма платежа как её видит кассир. */
  amount: string;
  symbol: string;
  /** Назначение платежа — кассир копирует его в поручение как есть. */
  memo: string;
  /** Состояние платежа в реестре кассирского стола. */
  status: string;
  /** Причина отказа, если кассир не смог заплатить. */
  message?: string;
  /** Получатель по реквизитам бюджета, если страна кооператива известна. */
  recipient_name?: string;
  /** Реквизиты бюджета снимком: пары «название — значение». */
  requisite_rows?: { label: string; value: string }[];
  created_at: Date;
  /** Когда кассир подтвердил перевод. */
  completed_at?: Date;
}

/** Запрос страницы. Нумерация страниц с единицы. */
export interface InnerWithheldTaxPageRequest {
  page: number;
  limit: number;
  sortOrder: 'ASC' | 'DESC';
}

export interface InnerWithheldTaxPage {
  items: InnerWithheldTaxPayment[];
  totalCount: number;
  totalPages: number;
  currentPage: number;
}

export interface IWithheldTaxPort {
  /** Сколько налога удержано, сколько уже у кассира и сколько можно отправить. */
  getState(coopname: string): Promise<InnerWithheldTaxState>;

  /** История отправленных на оплату сумм — от новых к старым. */
  listPayments(coopname: string, page: InnerWithheldTaxPageRequest): Promise<InnerWithheldTaxPage>;

  /**
   * Отправить сумму на оплату: заявка появляется у кассира в реестре исходящих
   * платежей. Больше доступного отправить нельзя — иначе те же деньги ушли бы
   * в бюджет дважды. Возвращает отправленную сумму.
   */
  createPayment(coopname: string, amount: number): Promise<string>;
}

