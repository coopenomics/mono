/**
 * Доверенности кооператива — системный учёт (решение владельца 18.11.2026).
 * Цепь хранит подписи доверенностей и встречные подписи; номер, срок и
 * состояние ведёт узел по событиям цепи. Провайдер — расширение кооперативных
 * участков (ku): оно выдаёт доверенности председателю участка и доверенным лицам.
 *
 * Потребители проверяют полномочия: истёкшая доверенность закрывает пайщику
 * работу по ней (например, работу с пунктом выдачи). Контракт по сроку не
 * блокирует — проверка только на узле.
 */

/** Тип доверенности. Новый тип добавляется в реестр типов провайдера. */
export type InnerPowerOfAttorneyType = 'branch_trustee' | 'branch_trusted';

/** Состояние доверенности на момент запроса. */
export type InnerPowerOfAttorneyStatus = 'pending' | 'active' | 'expired' | 'declined';

/** Пайщик, чьи полномочия по участку закрыты истёкшей доверенностью. */
export interface InnerLapsedAuthority {
  braname: string;
  username: string;
  type: InnerPowerOfAttorneyType;
  /** Последний день срока последней встречно подписанной доверенности, ISO 8601 (дата). */
  valid_until: string;
}

export interface IPowersOfAttorneyPort {
  /**
   * Пайщики кооператива с закрытыми полномочиями: у пайщика есть доверенность
   * по участку, и срок последней встречно подписанной истёк. Пайщик без
   * доверенности по участку в список не входит. Один запрос на кооператив —
   * потребитель держит ответ в своём кэше.
   */
  listLapsedAuthorities(coopname: string): Promise<InnerLapsedAuthority[]>;
}

