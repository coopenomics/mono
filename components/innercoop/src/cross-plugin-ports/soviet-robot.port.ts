/**
 * Робот решений совета (расширение `soviet-robot`): прямой рычаг для
 * расширений, которые ставят повестку и ждут решение здесь и сейчас.
 *
 * Робот и сам слушает цепь (событие новой повестки), но потребителю нужен
 * не факт «робот когда-нибудь дойдёт», а ответ в пределах ожидания у стойки:
 * Стол заказов ставит заявление о выдаче на повестку и держит пайщика в
 * режиме ожидания, пока совет не решит. Порт даёт такой вызов: «прими это
 * решение сейчас и скажи, чем кончилось». Если робот не установлен или у
 * членов совета не делегированы разрешения, порт отвечает `pending` — дальше
 * решение принимается вручную в повестке, а потребитель ждёт обратного вызова
 * контракта, сколько потребуется.
 *
 * Реализация — расширение-владелец `soviet-robot`; если оно не установлено,
 * мост регистрирует `null` (INV-013), потребитель обязан это пережить.
 */

export type InnerRobotDecisionOutcome =
  /** Решение утверждено и исполнено, обратный вызов контракта-инициатора отправлен. */
  | 'authorized'
  /** Совет отказал (голосов «против» достаточно), обратный вызов отказа отправлен. */
  | 'declined'
  /** Робот не может завершить сам: нет кворума делегировавших, ждём людей. */
  | 'pending'
  /** Робот выключен или тип решения не автоматизирован — только ручной путь. */
  | 'manual'
  /** Попытка робота упала (ошибка цепи, ключа); сторож робота повторит. */
  | 'failed';

export interface InnerRobotDecisionRequest {
  coopname: string;
  /** Номер решения в контракте soviet. */
  decision_id: number;
  /** Тип повестки (mktissue, mktretrn, …). */
  decision_type: string;
  /** Хэш повестки (order_hash / request_hash инициатора). */
  decision_hash: string;
  /** Пайщик, от имени которого подано заявление. */
  username: string;
}

export interface InnerRobotDecisionResult {
  outcome: InnerRobotDecisionOutcome;
  /** Транзакция утверждения/исполнения, если робот довёл решение до конца. */
  tx_hash?: string;
  /** Человекочитаемая причина для журнала потребителя (ошибка, кого ждём). */
  detail?: string;
}

export interface ISovietRobotPort {
  /** Робот установлен и включён в кооперативе. */
  isEnabled(): Promise<boolean>;
  /**
   * Взять решение в работу немедленно и дождаться исхода одного прохода
   * робота: голоса делегировавших, протокол председателя, утверждение и
   * исполнение. Возвращается, как только проход завершён — успехом, отказом
   * или остановкой на людях.
   */
  requestDecision(input: InnerRobotDecisionRequest): Promise<InnerRobotDecisionResult>;
}

