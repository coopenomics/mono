/**
 * Опознание пайщика по токену доступа.
 *
 * Порт для приложения, которое работает вне процесса ядра (контейнер из
 * каталога приложений): приложение получает запрос пайщика с токеном ядра, а
 * проверить токен само не может — секрета подписи у него нет и быть не
 * должно. С секретом приложение выпускало бы токен любого пайщика. Поэтому
 * приложение спрашивает ядро: чей это токен. Ядро проверяет подпись, тип и
 * живость сессии — ровно так же, как для своих запросов.
 */

/** Кто сделал запрос: по этим полям приложение проверяет права в своих операциях. */
export interface InnerAccessIdentity {
  /** Имя аккаунта пайщика в цепи. */
  username: string;
  /** Роль в кооперативе: `user`, `member`, `chairman`. */
  role: string;
  /** Статус учётной записи. */
  status: string;
}

export interface IAccessTokenPort {
  /**
   * Опознать пайщика по токену доступа. `null` — токен не принят: подпись не
   * сошлась, срок истёк, сессия завершена или это токен другого вида.
   */
  identify(token: string): Promise<InnerAccessIdentity | null>;
}

