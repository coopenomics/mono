/**
 * Назначаемые роли приложений.
 *
 * Роль придумывает и описывает приложение: какие права она даёт, записано в
 * его таблице прав. Ядро ролей не знает — оно ведёт только связь «роль —
 * пайщик»: кому роль назначена, кем и когда, и показывает объявленные роли
 * председателю на странице управления доступом.
 *
 * Приложение при запуске объявляет свои роли, а при расчёте прав пайщика
 * спрашивает, какие из них ему назначены.
 */

/** Роль, которую приложение даёт назначать пайщикам. */
export interface InnerAssignableRole {
  /**
   * Ключ роли — тот же, что в таблице прав приложения. Уникален среди всех
   * приложений кооператива: повтор ключа останавливает запуск.
   */
  key: string;
  /** Название роли для председателя: «Кассир». */
  title: string;
  /** Что роль открывает пайщику — одной фразой. */
  description: string;
}

export interface IRoleAssignmentsPort {
  /** Объявить назначаемые роли приложения. Зовётся один раз при запуске. */
  declare(extensionName: string, roles: readonly InnerAssignableRole[]): void;

  /** Роли приложения, назначенные пайщику сейчас. */
  rolesOf(extensionName: string, username: string): Promise<string[]>;
}

export const ROLE_ASSIGNMENTS_PORT = Symbol.for('Innercoop.CorePort.RoleAssignments');
