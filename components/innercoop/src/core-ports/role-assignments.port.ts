/**
 * Назначаемые роли приложений.
 *
 * Роль придумывает и описывает приложение: какие права она даёт, записано в
 * его таблице прав. Ядро ролей не знает — оно ведёт только связь «роль —
 * пайщик»: кому роль назначена, кем и когда, и показывает объявленные роли
 * председателю на странице управления доступом.
 *
 * Приложение при запуске объявляет свои роли, а при расчёте прав пайщика
 * спрашивает, какие из них ему назначены.
 */

/**
 * Полномочие роли словами: что пайщик с этой ролью читает или ведёт.
 * Показывается председателю на странице управления доступом.
 */
export interface InnerRolePermission {
  /** Что именно: «Реестр платежей кооператива». */
  title: string;
  /** `read` — пайщик видит, `write` — пайщик меняет. */
  access: 'read' | 'write';
  /** Права таблицы приложения `Ресурс:действие`, которые стоят за полномочием. */
  rights: readonly string[];
}

/** Роль, которую приложение даёт назначать пайщикам. */
export interface InnerAssignableRole {
  /**
   * Ключ роли — тот же, что в таблице прав приложения. Уникален среди всех
   * приложений кооператива: повтор ключа останавливает запуск.
   */
  key: string;
  /** Название роли для председателя: «Кассир». */
  title: string;
  /** Что роль открывает пайщику — одной фразой. */
  description: string;
  /** Полномочия роли по пунктам: вместе они называют все права роли из таблицы приложения. */
  permissions: readonly InnerRolePermission[];
}

/**
 * Дополнение к роли другого приложения. Роль объявлена один раз, но открывает
 * чтение или действия сразу в нескольких приложениях: ревизор читает и стол
 * совета, и стол бухгалтера. Каждое приложение называет полномочия по своей
 * таблице прав; права в чужой таблице роль от этого не получает.
 */
export interface InnerAttachedRole {
  /** Ключ роли, объявленной другим приложением. */
  key: string;
  /** Полномочия роли в этом приложении: вместе они называют её права в его таблице. */
  permissions: readonly InnerRolePermission[];
}

export interface IRoleAssignmentsPort {
  /** Объявить назначаемые роли приложения. Зовётся один раз при запуске. */
  declare(extensionName: string, roles: readonly InnerAssignableRole[]): void;

  /**
   * Присоединить полномочия приложения к ролям, объявленным другими
   * приложениями. Роль без объявления останавливает запуск узла.
   */
  attach(extensionName: string, roles: readonly InnerAttachedRole[]): void;

  /** Роли, назначенные пайщику сейчас: объявленные приложением и те, к которым оно присоединилось. */
  rolesOf(extensionName: string, username: string): Promise<string[]>;
}

export const ROLE_ASSIGNMENTS_PORT = Symbol.for('Innercoop.CorePort.RoleAssignments');
