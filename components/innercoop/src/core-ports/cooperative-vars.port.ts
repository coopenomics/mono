/**
 * Реквизиты кооператива, которому принадлежит контур: как он называется и как
 * его называть в текстах.
 *
 * Нужны расширениям, которые формируют обращённый к человеку текст — заголовок
 * чата, тему письма, строку уведомления. В ядре за этим ходили в
 * `VarsRepository`, отдающий два десятка полей вплоть до номеров соглашений и
 * ссылок на политику конфиденциальности. Расширения из них читают ровно три:
 * `name` (9 обращений), `short_abbr` (8), `coopname` (1) — поэтому порт отдаёт
 * их, а не весь объект. Остальное — дело ядра, и расширению незачем это видеть.
 */
export interface InnerCooperativeVars {
  /** Учётное имя кооператива в цепи, например `voskhod`. */
  coopname: string;
  /** Полное человеческое название, например «Потребительский кооператив "Восход"». */
  name: string;
  /** Краткое название для заголовков и подписей, например «ПК "Восход"». */
  shortAbbr: string;
}

export interface ICooperativeVarsPort {
  /**
   * Прочитать реквизиты. `null` — реквизиты ещё не заведены: контур поднят, но
   * кооператив не сконфигурирован. Потребитель обязан пережить этот случай.
   */
  get(): Promise<InnerCooperativeVars | null>;
}

