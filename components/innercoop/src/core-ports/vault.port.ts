/**
 * Ключи подписи, хранимые кооперативом.
 *
 * Расширение подписывает транзакции от имени аккаунта кооператива, поэтому
 * ключ ему нужен, но храниться и расшифровываться он обязан в ядре: за
 * пределами монолита нет ни таблицы хранилища, ни ключа шифрования. Раньше
 * расширения инжектили `VaultDomainService` по пути `~/domain/vault`.
 *
 * Порт **не скоупит доступ**: он отдаёт ключ любому, кто спросил, — право
 * подписывать от имени этого аккаунта вызывающий проверяет до обращения сюда.
 * Полученный ключ нельзя логировать, класть в ответ API и передавать дальше.
 */

/**
 * Уровень полномочий ключа. Пока единственный: активный ключ, которым
 * подписывают обычные действия.
 */
export enum InnerKeyPermission {
  ACTIVE = 'active',
}

export interface IVaultPort {
  /**
   * Расшифрованный ключ подписи; `null`, если для аккаунта его нет.
   *
   * Отсутствие ключа — рабочая ситуация, а не сбой: у пайщика, подписывающего
   * сам, кооператив ключа не держит.
   */
  getWif(username: string, permission?: InnerKeyPermission): Promise<string | null>;
}

export const VAULT_PORT = Symbol.for('Innercoop.CorePort.Vault');
