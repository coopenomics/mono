/**
 * Декларация документов приложения — какие шаблоны реестра документов оно
 * использует в кооперативе и какие из них совет обязан утверждать.
 *
 * Из деклараций установленных приложений и базового набора ядра складывается
 * реестр шаблонов кооператива: по нему совет видит утверждённую и доступную
 * редакцию каждого документа и выносит новые редакции на решение. Шаблон,
 * которого ни одно установленное приложение не объявило, в реестре не
 * появляется — утвердить документ приложения, которого нет, нельзя.
 *
 * Расширение объявляет документы при запуске, снимает — ядро само при
 * остановке расширения. Утверждения в цепи при этом остаются: они привязаны к
 * документу и кооперативу, а не к установке.
 */

/**
 * Род документа.
 *
 * - `agreement` — подписывают пайщики (политика, оферты ЦПП, соглашение о
 *   кошельке): новая редакция после утверждения требует переподписания;
 * - `provision` — утверждает совет, пайщики не подписывают (положения ЦПП,
 *   шаблоны договоров);
 * - `form` — заявления, акты, накладные: утверждается как форма, экземпляры
 *   порождаются по событиям, переподписания нет;
 * - `service` — повестка, протоколы решений, бюллетени: форма задана уставом
 *   или законом, утверждение не требуется.
 */
export type InnerDocumentKind = 'agreement' | 'provision' | 'form' | 'service';

/** Нужно ли решение совета, чтобы редакция документа действовала в кооперативе. */
export type InnerDocumentApproval = 'required' | 'none';

export interface InnerDocumentDeclaration {
  /** Расширение-владелец; базовый набор ядра объявляется под именем `core`. */
  extension_name: string;
  /** Номер шаблона в реестре документов платформы. */
  registry_id: number;
  kind: InnerDocumentKind;
  approval: InnerDocumentApproval;
  /**
   * Ключ пакета: документы одного пакета утверждаются одним решением совета.
   * Для документов, унаследовавших шаг онбординга, совпадает с ключом шага.
   */
  bundle?: string;
  /**
   * Поле `vars` кооператива, куда фабрика пишет реквизиты протокола
   * (`protocol_number`, `protocol_day_month_year`) — их подставляют шаблоны.
   */
  vars_field?: string;
  /** Название для реестра; по умолчанию берётся из шаблона в цепи. */
  title?: string;
  /** Порядок в списке приложения: сверху вниз. */
  order: number;
}

export interface IDocumentDeclarationPort {
  /**
   * Объявить документы приложения. Повторное объявление той же пары
   * (расширение, шаблон) заменяет прежнее; один шаблон двум расширениям
   * принадлежать не может.
   */
  registerDocuments(declarations: InnerDocumentDeclaration[]): Promise<void>;
  /** Снять все декларации расширения — при остановке или переустановке. */
  unregisterByExtension(extension_name: string): Promise<void>;
}

export const DOCUMENT_DECLARATION_PORT = Symbol.for('Innercoop.CorePort.DocumentDeclaration');
