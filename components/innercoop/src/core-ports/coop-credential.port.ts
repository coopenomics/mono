/**
 * Удостоверение кооператива в сети: чем он подписывает свои свидетельства и чем
 * доказывает, что сеть его признаёт.
 *
 * Нужен расширениям, которые выпускают наружу подписанные документы от имени
 * кооператива, — таким, что проверяются третьей стороной без обращения к
 * выпустившему. Первый потребитель — «Карта пайщика»: подтверждение членства
 * подписывается ключом заверения и едет вместе с цепочкой признания.
 *
 * Ключ порт **не отдаёт**. Он подписывает переданные байты и возвращает подпись:
 * иначе ключ заверения расходился бы копиями по расширениям, а его компрометация
 * означает, что все выпущенные кооперативом удостоверения перестают проверяться.
 * Тем же соображением ключ подписи транзакций отдаётся (`VAULT_PORT`), а этот —
 * нет: там ключ нужен библиотеке цепи целиком, здесь достаточно подписи.
 */

/** Звено цепочки признания — заверение в компактной форме JWS, как оно лежит в цепи. */
export type InnerEndorsementCredential = string;

export interface ICoopCredentialPort {
  /**
   * Подписывает байты ключом заверения кооператива.
   *
   * @param message — канонический байтовый образ документа; что именно
   *   канонизировать и как, решает вызывающий: подпись накрывает ровно эти байты.
   * @returns Подпись в формате цепи (`SIG_K1_…`).
   * @throws Если ключа заверения у кооператива нет — подписывать нечем.
   */
  signWithCertKey(message: Uint8Array): Promise<string>;

  /**
   * Цепочка признания от корня доверия к этому кооперативу.
   *
   * Порядок — от корня к кооперативу: проверяющий идёт по ней сверху вниз, и
   * обратный порядок он не примет. Пустой массив означает, что кооператив в сети
   * пока не признан: выпускать удостоверения технически можно, но проверить их
   * будет нечем.
   */
  getTrustChain(): Promise<InnerEndorsementCredential[]>;

  /**
   * Сеть, в которой действует удостоверение.
   *
   * Входит в подписываемые документы: без неё документ, выпущенный в подсети,
   * приняли бы в главной цепи, и наоборот.
   */
  getChainId(): Promise<string>;
}

export const COOP_CREDENTIAL_PORT = Symbol.for('Innercoop.CorePort.CoopCredential');
