/**
 * Логотип кооператива — одно изображение в настройках узла, хранится ядром.
 *
 * Столы расширений (Стол заказов) показывают его в шапке профиля кооператива
 * рядом с обложкой и названием и меняют его там же. Своей копии файла и своей
 * записи в базе расширение не держит: и чтение, и запись идут через этот порт.
 * Ссылка временная (подписанная), поэтому её не сохраняют — запрашивают на
 * каждый показ.
 */
export interface ICooperativeLogoPort {
  /** Ссылка на логотип кооператива; `null` — логотипа нет, показываются инициалы. */
  getLogoUrl(): Promise<string | null>;

  /** Загрузить логотип из base64; вернуть подписанную ссылку на новый файл. */
  upload(contentBase64: string, mimeType: string): Promise<string>;

  /** Снять логотип — в шапке останутся инициалы. */
  remove(): Promise<void>;
}

export const COOPERATIVE_LOGO_PORT = Symbol.for('Innercoop.CorePort.CooperativeLogo');
