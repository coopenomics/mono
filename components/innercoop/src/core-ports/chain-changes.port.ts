/**
 * Лента изменений цепи — сигнал столу «эти данные изменились, перечитай».
 *
 * Узел разбирает блок и, когда дельты сохранены и их слушатели отработали,
 * сообщает подписчикам: в таблице такой-то изменилась строка, блок такой-то.
 * Данных в сигнале нет — стол дочитывает авторитетное состояние запросом.
 *
 * В ленту попадают только объявленные таблицы. Ядро объявляет свои,
 * расширение — свои, при запуске. У личной таблицы указывается поле строки с
 * именем пайщика-владельца: такой сигнал получает только владелец и совет, а
 * не весь кооператив — иначе пополнение одного кошелька заставляло бы
 * перечитываться всех.
 */
export interface InnerChainChangesTable {
  /** Аккаунт контракта в цепи — `<Contract>.contractName.production`. */
  code: string;
  /** Имя таблицы — `<Contract>.Tables.<Table>.tableName`. */
  table: string;
  /**
   * Поле строки с именем пайщика-владельца (обычно `username`). Задано —
   * таблица личная: сигнал уходит владельцу и совету. Не задано — всем
   * пайщикам кооператива.
   */
  owner_field?: string;
}

export interface IChainChangesPort {
  /**
   * Объявить таблицы для ленты. Повторное объявление той же таблицы заменяет
   * прежнее.
   */
  declareTables(tables: InnerChainChangesTable[]): void;
}

export const CHAIN_CHANGES_PORT = Symbol.for('Innercoop.CorePort.ChainChanges');
