/**
 * Лента изменений цепи — сигнал столу «эти данные изменились, перечитай».
 *
 * Узел разбирает блок и, когда дельты сохранены и их слушатели отработали,
 * сообщает подписчикам: в таблице такой-то изменилась строка, блок такой-то.
 * Данных в сигнале нет — стол дочитывает авторитетное состояние запросом.
 *
 * В ленту попадают только объявленные таблицы. Ядро объявляет свои,
 * расширение — свои, при запуске. У личной таблицы указывается поле строки с
 * именем пайщика-владельца: такой сигнал получает только владелец и персонал
 * (совет и назначенные расширением), а не весь кооператив — иначе пополнение
 * одного кошелька заставляло бы перечитываться всех.
 *
 * Данные расширения вне цепи (курсы, записи, задачи) объявляются таблицами
 * базы узла: сигнал уходит сам, когда запись в такую таблицу зафиксирована, —
 * расставлять вызовы после каждого сохранения не нужно.
 */
export interface InnerChainChangesTable {
  /**
   * Аккаунт контракта в цепи — `<Contract>.contractName.production`; у таблиц
   * базы узла — имя расширения.
   */
  code: string;
  /** Имя таблицы — `<Contract>.Tables.<Table>.tableName` либо имя из `@Entity`. */
  table: string;
  /**
   * Поле строки с именем пайщика-владельца (обычно `username`) либо со
   * списком имён — тогда сигнал уходит каждому. Задано — таблица личная:
   * сигнал уходит владельцам и персоналу. Не задано — всем пайщикам кооператива.
   */
  owner_field?: string;
  /** Только персоналу: совету и назначенным расширением (задачи, настройки). */
  staff_only?: boolean;
}

export interface IChainChangesPort {
  /**
   * Объявить таблицы для ленты. Повторное объявление той же таблицы заменяет
   * прежнее.
   */
  declareTables(tables: InnerChainChangesTable[]): void;

  /**
   * Объявить таблицы базы узла, которые пишет расширение (`table` — имя из
   * `@Entity`, `owner_field` — свойство сущности). Сигнал уходит после
   * фиксации транзакции записи; номер блока у него 0.
   */
  declareLocalTables(tables: InnerChainChangesTable[]): void;

  /**
   * Персонал расширения — кто кроме совета получает личные и служебные
   * таблицы расширения (`code`). Передаётся список, а не проверка: при смене
   * состава расширение передаёт его заново.
   */
  setStaff(code: string, usernames: string[]): void;

  /**
   * Опубликовать изменение строки объявленной таблицы базы узла, когда запись
   * прошла мимо подписчика ядра: сырой SQL или своя база расширения (её
   * расширение наблюдает само — `LocalChangesCollector` из extension-kit).
   * Звать после фиксации записи; `row` — для владельца личной таблицы.
   */
  publishLocal(table: string, primary_key: string, row?: Record<string, unknown>): Promise<void>;
}

export const CHAIN_CHANGES_PORT = Symbol.for('Innercoop.CorePort.ChainChanges');
