/**
 * Шифрование секретов расширения.
 *
 * Расширение хранит свои секреты — токен доступа к внешней службе, пароль
 * учётной записи мессенджера — в собственной настройке, но шифрует их общим
 * ключом кооператива. Ключ и алгоритм остаются в ядре: за пределами монолита
 * ключа нет, а расшифровать чужой секрет расширение и не должно уметь само.
 *
 * Строка шифротекста самодостаточна: в ней и вектор инициализации, и данные,
 * поэтому её можно хранить как обычное значение настройки. Смена ключа
 * кооператива делает прежние строки нечитаемыми — это не сбой шифра, а
 * следствие смены ключа; расшифровка в таком случае бросает.
 */
export interface ISecretCipherPort {
  encrypt(plaintext: string): string;

  /** Бросает, если строка повреждена или зашифрована другим ключом. */
  decrypt(ciphertext: string): string;
}

export const SECRET_CIPHER_PORT = Symbol.for('Innercoop.CorePort.SecretCipher');
