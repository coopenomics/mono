/**
 * Фотография пайщика — одна на аккаунт, хранится ядром.
 *
 * Пайщик загружает её в удостоверении пайщика либо на столе расширения (профиль
 * преподавателя), а показывается она везде, где платформа рисует человека.
 * Расширение за чужой таблицей не ходит и файл само не хранит: спрашивает
 * ссылку здесь и отдаёт её своему столу.
 *
 * Ссылка временная (подписанная), поэтому её не сохраняют — запрашивают на
 * каждый показ.
 */
export interface IUserAvatarPort {
  /** Ссылка на фотографию пайщика; `null` — фотографии нет. */
  getAvatarUrl(username: string): Promise<string | null>;

  /** Ссылки сразу для нескольких пайщиков: реестр рисует список одним запросом. */
  getAvatarUrls(usernames: string[]): Promise<Map<string, string>>;
}

export const USER_AVATAR_PORT = Symbol.for('Innercoop.CorePort.UserAvatar');
