import type { InnerAccountType } from './account.port';

/**
 * Личные данные пайщика записаны: председатель загрузил пайщика списком или
 * данные пайщика исправлены.
 *
 * Событие слушают расширения, которые держат у себя выборку по личным данным
 * (например, календарь дней рождения): склад данных пайщиков хранит их в jsonb
 * без индексов, и расширение не перечитывает его целиком, а обновляет свою
 * выборку по событию.
 *
 * Дата рождения передаётся в событии, а не перечитывается подписчиком: ядро
 * записывает данные и публикует событие без ожидания записи, и чтение сразу
 * после события может вернуть прежнюю версию.
 */
export const PARTICIPANT_PROFILE_UPDATED_EVENT = 'participant::profile-updated' as const;

export interface InnerParticipantProfileUpdatedEvent {
  username: string;
  account_type: InnerAccountType;
  /**
   * Дата рождения из записанных данных — у физического лица и индивидуального
   * предпринимателя; у организации `null`.
   */
  birthdate: string | null;
}
