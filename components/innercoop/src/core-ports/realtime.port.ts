/**
 * Шина событий реального времени — то, из чего кормятся подписки клиента.
 *
 * Расширение публикует в неё свои события и подписывает на них резолвер, а
 * устройство шины остаётся в ядре: сегодня она внутрипроцессная, потому что
 * контроллер обслуживает один кооператив одним процессом; при переходе на
 * несколько процессов заменится реализация, а не потребители.
 *
 * Событие живёт ровно столько, сколько идёт доставка: кто не подписан в момент
 * публикации, его не увидит. Всё, что обязано пережить перезапуск, пишется в
 * базу, а шина лишь сообщает, что там появилось.
 */
export interface IRealtimeChannelPort {
  /** Опубликовать событие подписчикам канала. */
  publish(trigger: string, payload: Record<string, any>): Promise<void>;

  /** Поток событий канала — им резолвер отвечает на подписку. */
  asyncIterator<T = any>(trigger: string | string[]): AsyncIterator<T>;
}

export const REALTIME_CHANNEL_PORT = Symbol.for('Innercoop.CorePort.RealtimeChannel');
