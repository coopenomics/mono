/**
 * Пояснение председателя к отклонению решения совета.
 *
 * Отклонение по большинству голосов «против» несёт в цепи одну общую фразу.
 * Председатель может пояснить отказ своими словами; пояснение хранит ядро в
 * базе узла (в цепь оно не пишется) и отдаёт по номеру решения. Расширение,
 * получившее обратный вызов отклонения, показывает пояснение своему
 * пользователю — например, преподавателю в отчёте по занятию. Пояснения нет —
 * расширение показывает основание из цепи.
 */
export interface IDecisionDeclineReasonPort {
  /** Пояснение председателя к отклонению решения или `null`, если он его не писал. */
  getDeclineReason(coopname: string, decisionId: string | number): Promise<string | null>;
}

export const DECISION_DECLINE_REASON_PORT = Symbol.for('Innercoop.CorePort.DecisionDeclineReason');
