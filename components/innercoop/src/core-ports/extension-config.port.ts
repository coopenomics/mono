/**
 * Настройка установленного расширения.
 *
 * Своя настройка приходит расширению при запуске, но иногда нужна и чужая:
 * например, Стол заказов смотрит, принята ли программа кооперативом. Читать
 * настройку соседа напрямую нельзя — ходить надо сюда.
 *
 * Настройка может быть недоступна: расширение не установлено в кооперативе.
 * Это рабочий случай, а не сбой, и потребитель обязан пережить `null`
 * поведением по умолчанию.
 */
export interface IExtensionConfigPort {
  get<T = Record<string, any>>(extensionName: string): Promise<T | null>;
}

export const EXTENSION_CONFIG_PORT = Symbol.for('Innercoop.CorePort.ExtensionConfig');
