/**
 * Доступы к внешним службам: мессенджер, распознавание речи, видеосвязь,
 * геокодер, хостинг репозиториев.
 *
 * Настройки таких служб — адреса, ключи, пароли — задаются один раз при
 * развёртывании контура и хранятся в ядре. Расширение получает их отсюда и
 * никогда не читает окружение само: за пределами монолита окружения ядра нет,
 * а ключ, попавший в настройку расширения, стал бы виден всем, кто эту
 * настройку правит.
 *
 * Через настройки контура (`platformSettings`) эти значения не передаются
 * намеренно: там несекретное и общее, а здесь — то, чем можно
 * воспользоваться от имени кооператива.
 *
 * **Доступ ограничен списком.** Расширение называет себя и службу; ядро
 * сверяется, разрешена ли ему эта служба, и на неразрешённую отвечает `null` —
 * так же, как на ненастроенную. Это не защита от злонамеренного кода в своём
 * же процессе, а страховка от случайной связи: расширение, потянувшее чужой
 * ключ, обнаружит это сразу, а не в проде.
 */
export interface IIntegrationSettingsPort {
  /**
   * Настройки службы для расширения.
   *
   * `null` означает одно из двух: службы нет в списке разрешённых этому
   * расширению или она не сконфигурирована в контуре. Различать эти случаи
   * потребителю незачем — в обоих он обязан работать без неё.
   */
  get<T = Record<string, any>>(extensionName: string, integration: string): T | null;
}

export const INTEGRATION_SETTINGS_PORT = Symbol.for('Innercoop.CorePort.IntegrationSettings');
