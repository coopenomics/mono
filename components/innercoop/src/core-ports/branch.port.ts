/**
 * Кооперативные участки — территориальные подразделения кооператива.
 *
 * Расширение спрашивает, кто доверенный участка и кто в него входит, чтобы
 * решить, кому показывать заказ и от чьего имени проводить выплату. Заводит и
 * меняет участки ядро: это решение совета, а не действие расширения. Раньше
 * инжектился `BRANCH_BLOCKCHAIN_PORT` по пути `~/domain/branch`, которого за
 * пределами монолита нет.
 */

/**
 * Участок, как он записан в цепи.
 *
 * Перечислены поля, которые читают расширения; остальные доступны через
 * индексную сигнатуру — переписывать всю форму цепи значило бы держать её в
 * синхронизации вручную.
 */
export interface InnerBranch {
  /** Учётное имя участка в цепи. */
  braname: string;
  /** Доверенное лицо участка — от его имени идут выплаты и приёмки. */
  trustee: string;
  /** Уполномоченные участка помимо доверенного. */
  trusted: string[];
  /** Закрытый участок виден не всем пайщикам. Поле появилось позже, у старых записей его нет. */
  is_private?: boolean;
  whitelist?: string[];
  [key: string]: any;
}

export interface IBranchPort {
  getBranches(coopname: string): Promise<InnerBranch[]>;

  /** Участок по имени; `null`, если такого нет. */
  getBranch(coopname: string, braname: string): Promise<InnerBranch | null>;
}

export const BRANCH_PORT = Symbol.for('Innercoop.CorePort.Branch');
