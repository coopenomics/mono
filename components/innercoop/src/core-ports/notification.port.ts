/**
 * Центр уведомлений: расширение говорит, ЧТО и КОМУ отправить, не зная про
 * каналы, шаблоны и провайдеров.
 *
 * Порт уже существовал в ядре как `NotificationPort` и уже инжектился
 * расширениями по токену — переехал потому, что жил по пути `~/domain/**`,
 * которого за пределами монолита нет.
 *
 * Реализация пишет строки в транзакционный outbox в той же транзакции, что и
 * вызывающий сервис; фактическую доставку выполняет фоновый обработчик. Поэтому
 * успешный `notify` означает «принято к доставке», а не «доставлено».
 */

/** Получатель уведомления. */
export interface InnerNotifyRecipient {
  /**
   * Идентификатор подписчика, выданный при онбординге. Неизменен между
   * перезапусками, поэтому адресуемся именно им, а не учётным именем.
   */
  subscriberId: string;
  /** Почта получателя, если подтверждена, — без неё канал почты недоступен. */
  email?: string;
  /** Учётное имя в кооперативе: для адресации внутри интерфейса и журнала. */
  username?: string;
}

/** Кто инициировал уведомление — показывается получателю как «от кого». */
export interface InnerNotifyActor {
  subscriberId: string;
  email?: string;
}

export interface InnerNotifyInput {
  /**
   * Кооператив-владелец уведомления. Обязателен: каждый кооператив доставляет
   * своим подписчикам сам, точка доставки локальна.
   */
  coopname: string;
  /**
   * Тип уведомления из каталога `@coopenomics/notifications`. Каталог хранит
   * каналы и шаблоны, поэтому здесь достаточно идентификатора.
   */
  workflowId: string;
  /** Один получатель или несколько — рассылка по участникам кооператива. */
  to: InnerNotifyRecipient | InnerNotifyRecipient[];
  /** Данные для подстановки в шаблон; проверяются схемой типа из каталога. */
  payload?: Record<string, unknown>;
  actor?: InnerNotifyActor;
}

/** Итог постановки уведомления в очередь доставки. */
export interface InnerNotifyResult {
  /** Принято к доставке: строки очереди записаны. */
  acknowledged: boolean;
  /** Идентификаторы созданных строк очереди — по получателям и каналам. */
  outboxIds: string[];
}

export interface INotificationPort {
  /**
   * Поставить уведомление в очередь доставки.
   *
   * Идемпотентно по ключу, вычисляемому из типа, получателя и события:
   * повторный вызов с теми же данными ничего не делает. Поэтому повтор после
   * сетевого сбоя безопасен.
   */
  notify(input: InnerNotifyInput): Promise<InnerNotifyResult>;

  /**
   * То же, но получатель указан учётным именем.
   *
   * Отдельная операция, потому что перевод имени в подписчика требует доступа к
   * учётным записям, а расширению для одного уведомления заводить его незачем.
   * Бросает, если у пайщика нет идентификатора подписчика: молча не отправить
   * уведомление хуже, чем упасть.
   */
  notifyUser<T extends Record<string, unknown>>(
    username: string,
    workflowId: string,
    payload: T,
    actor?: InnerNotifyActor
  ): Promise<InnerNotifyResult>;
}

