/**
 * Тариф кооператива у провайдера подключения: объём документооборота и
 * суточный расход D (@ant 17.10.2026, «Оплата документооборота: бак AXON,
 * объём тарифа и кванты»).
 *
 * По дате оплаты в бак кооператива приходит объём месяца в AXON. Узел жжёт бак
 * сам: каждый день арендует ресурсы на D = объём / число дней месяца, чтобы
 * бак опустел ровно к следующей оплате. D считает провайдер — у него тариф и
 * календарь, узлу остаётся спросить и арендовать.
 */

export interface InnerProviderTariff {
  /** Код тарифа. */
  code: string;
  /** Объём документооборота на месяц, AXON. */
  docflow_axon: number;
  /** Суточный расход на текущий календарный месяц, AXON; без округления. */
  daily_axon: number;
  /** Пробный период тарифа, дней. */
  trial_days: number;
}

export interface IProviderTariffPort {
  /**
   * Тариф кооператива; `null`, если провайдер не настроен, не отвечает или
   * тариф не выбран. Отказ провайдера сюда не пробрасывается: узел без тарифа
   * продолжает арендовать по своей настройке.
   */
  currentTariff(coopname: string): Promise<InnerProviderTariff | null>;
}

export const PROVIDER_TARIFF_PORT = Symbol.for('Innercoop.CorePort.ProviderTariff');
