/**
 * Отдельная база расширения.
 *
 * Расширение, которое держит своё состояние в собственном подключении, обязано
 * знать, куда подключаться, — но не обязано знать, откуда это известно ядру.
 * Раньше за реквизитами шли прямо в `~/config/config` контроллера, то есть по
 * пути, которого за пределами монолита нет.
 *
 * Через настройки контура (`platformSettings` каркаса) реквизиты не передаются
 * намеренно: там несекретное и общее, а здесь пароль от базы.
 *
 * **Доступ ограничен списком**, как и у доступов к внешним службам: расширение
 * называет себя, ядро сверяется, заведена ли ему база, и на незаведённую
 * отвечает `null`. Это страховка от случайной связи, а не защита от
 * злонамеренного кода в своём же процессе.
 *
 * Сущности перечисляет само расширение — что лежит в его базе, ядру знать
 * незачем.
 */
export interface InnerExtensionDatabaseConnection {
  host: string;
  port: number;
  username: string;
  password: string;
  /** Имя базы. */
  database: string;
}

export interface IExtensionDatabasePort {
  /**
   * Реквизиты подключения, заведённого расширению.
   *
   * `null` — расширению отдельная база не заведена; работать оно обязано на
   * общем подключении ядра.
   */
  getConnection(extensionName: string): InnerExtensionDatabaseConnection | null;
}

export const EXTENSION_DATABASE_PORT = Symbol.for('Innercoop.CorePort.ExtensionDatabase');
