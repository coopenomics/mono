/**
 * Именованный канал сообщений контура кооператива: публикация и подписка.
 *
 * Сегодня за портом стоит Redis pub/sub, но расширение об этом знать не должно —
 * потому контракт и назван по тому, что он делает, а не по вендору. В ядре порт
 * назывался `RedisPort` и лежал в `~/domain/common/ports`; для контрактного
 * пакета такое имя было бы противоречием.
 *
 * **Это не шина доменных событий.** Канал переносит произвольное сообщение
 * между процессами (сегодня — уведомления платёжных расширений о смене статуса
 * платежа). Межрасширенческая шина доменных событий с обязательным `coopname`
 * в payload (INV-012) — отдельный будущий контракт; смешивать их нельзя, иначе
 * либо шина потеряет инвариант, либо у канала появится поле, которого его
 * потребителям неоткуда взять.
 */
export interface IMessageChannelPort {
  /** Опубликовать сообщение в канал. Доставка — best-effort, без подтверждения. */
  publish(channel: string, message: any): Promise<void>;

  /** Подписаться на канал. Обработчик вызывается на каждое сообщение. */
  subscribe(channel: string, handler: (message: any) => void): void;
}

