/**
 * Типы страновых справочников.
 *
 * Всё, что здесь описано, — данные, а не поведение: реквизиты, коды, ставки,
 * часовой пояс. Решения на их основе принимает вызывающий код, справочник
 * только отвечает «что действовало в такой-то стране на такую-то дату».
 */

/**
 * Код страны регистрации кооператива. Совпадает со значениями enum `Country`
 * контроллера — иначе пришлось бы держать таблицу соответствия, которая
 * разъедется при добавлении страны.
 */
export type JurisdictionCode = 'Russia';

/**
 * Запись, действующая с определённой даты.
 *
 * Реквизиты бюджета и налоговые коды меняются приказами, и меняются часто:
 * КПП получателя ЕНП сменился 5 декабря 2025, назначение платежа — 1 апреля
 * 2026. Хранить только текущее значение нельзя: платёж или отчёт за прошлый
 * период пересобрался бы по сегодняшним правилам и разошёлся бы с тем, что
 * реально ушло в банк.
 */
export interface EffectiveRecord<T> {
  /** Дата вступления в силу, ГГГГ-ММ-ДД. */
  effectiveFrom: string;
  value: T;
}

/** Строка реквизита платёжного поручения: название и значение. */
export interface PaymentRequisiteRow {
  label: string;
  value: string;
}

/** Куда и с каким назначением перечисляется удержанный налог. */
export interface TaxTransferRequisites {
  /** Назначение платежа — плательщик копирует его в банк как есть. */
  memo: string;
  /** Получатель платежа. */
  recipientName: string;
  /** Остальные реквизиты в порядке заполнения платёжного поручения. */
  rows: PaymentRequisiteRow[];
}

/** Налог на доходы физических лиц: ставка и коды, по которым он платится. */
export interface PersonalIncomeTax {
  /** Ставка в целых процентах. */
  ratePercent: number;
  /** КБК самого налога — им помечается уведомление об исчисленных суммах. */
  kbk: string;
  /**
   * Код вида дохода «материальная помощь» лицу, которое работником не
   * является: у выплаты работнику код и правила вычета другие.
   */
  aidIncomeCode: string;
}

/**
 * Страновой профиль. Растёт по мере надобности: сюда попадает то, что уже
 * понадобилось коду, а не гипотезы о чужих юрисдикциях.
 */
export interface JurisdictionProfile {
  code: JurisdictionCode;
  /**
   * Часовой пояс, по которому определяются налоговые сроки, — смещение от UTC
   * в минутах. Блокчейн ставит отметки в UTC, а срок перечисления налога
   * считается по местному времени, и на границе суток это разные периоды.
   */
  taxTimezoneOffsetMinutes: number;
  /** Реквизиты перечисления удержанного налога по датам вступления в силу. */
  taxTransfer: EffectiveRecord<TaxTransferRequisites>[];
  /** Параметры НДФЛ (или его местного аналога) по датам вступления в силу. */
  personalIncomeTax: EffectiveRecord<PersonalIncomeTax>[];
}
