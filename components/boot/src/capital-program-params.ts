function stableStringify(value: unknown): string {
  if (value === null || typeof value !== 'object')
    return JSON.stringify(value)
  if (Array.isArray(value))
    return `[${value.map(item => stableStringify(item)).join(',')}]`
  const entries = Object.keys(value as Record<string, unknown>)
    .sort()
    .map(key => `${JSON.stringify(key)}:${stableStringify((value as Record<string, unknown>)[key])}`)
  return `{${entries.join(',')}}`
}

/** Хэш параметров — тот, что фабрика вернула бы при сохранении через стол. */
export function capitalProgramDocDataHash(): string {
  return createHash('sha256').update(Buffer.from(stableStringify(capitalProgramPrivateData), 'utf8')).digest('hex').toUpperCase()
}
