#!/usr/bin/env bash
# Псевдоним `pnpm run reboot` — оставлен, чтобы не ломать привычную команду и
# ссылки в заметках.
#
# Раньше отличался от reboot.sh тем, что действительно сносил тома и не трогал
# сеть компоуза, — reboot этого не умел. Теперь обе вещи делает общий
# lib/stack.sh, и различий не осталось. Держать вторую копию тех же шагов —
# верный способ однажды поправить только одну из них.

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
exec bash "$SCRIPT_DIR/reboot.sh" "$@"
