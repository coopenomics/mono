#!/usr/bin/env node
// Сюита «экономика участка по итогу месяца» — часть сценариев Стола заказов,
// которым нужен рассчитанный итог месяца участка (99D-23).
//
// Участок получает членский взнос первого числа: из обеспечительной части
// паевых взносов ему достаются его расходы. В настоящем времени итога не
// дождаться, и общий кошелёк участка пуст — поэтому эти сценарии сняты с
// основной сюиты (bin/run-marketplace-all.mjs) и идут здесь, на отдельном
// стенде CI:
//   - стенд засеян фазой `stack.sh seed` (участки, поставщик с предложениями,
//     пайщики) и переведён на сжатое время `stack.sh standtime compress`;
//   - фаза подготовки `mktkeu:01-common` (api-tests/src/seed/mktkeu) проводит
//     заказ через API до выдачи и дожидается итога месяца — до первого входа
//     пайщиков со стола, пока их ключи из фикстур действуют;
//   - сценарии только смотрят и распределяют: экраны «Экономика участка» с
//     деньгами, итоги месяцев со строкой итога, карточка заказа со списанной
//     обеспечительной частью.
//
// Запуск в CI: ветка-полигон ci/ui-docs-marketplace-keu (workflow ui-docs).
// Месяц на кадрах итогов подписан отрезком времени стенда, а не названием
// месяца: так стол подписывает периоды короче суток.

import { runSuite } from '../lib/suite.mjs';

const GROUPS = [
  {
    name: 'Экономика участка по итогу месяца (сжатое время стенда)',
    scenarios: [
      'marketplace/operator/branch-economy',
      'marketplace/branch-chairman/economy-reserve-periods',
      'marketplace/orderer/order-secure-part-charged',
    ],
  },
];

process.exit(await runSuite({ app: 'marketplace', groups: GROUPS, args: process.argv.slice(2), partial: true }));
