/**
 * @brief Отказ председателя совета в подписи акта приёма-передачи имущества
 * не допускается (registry 1122; задача 99D-27). Вызывается контрактом совета
 * (`soviet::declineapprv`) и всегда отклоняет отказ — тогда отклоняется и
 * declineapprv, одобрение остаётся на подписи.
 *
 * Почему: решение о приёме имущества уже принял совет, подпись председателя
 * под актом — техническое исполнение этого решения, отказать в ней нельзя
 * (решение владельца 08.11.2026). Обратный вызов отказа нужен совету как
 * обязательный параметр одобрения, поэтому действие есть, но ничего не меняет.
 *
 * @ingroup public_marketplace_actions
 */
void marketplace::dclipact(eosio::name coopname, eosio::name username,
                           checksum256 property_hash, std::string reason) {
  require_auth(_soviet);
  eosio::check(false,
               "MARKETPLACE_IPROP_ACT_DECLINE_FORBIDDEN: Совет уже принял решение о приёме имущества — "
               "председатель подписывает акт, отказ в подписи не предусмотрен");
}
