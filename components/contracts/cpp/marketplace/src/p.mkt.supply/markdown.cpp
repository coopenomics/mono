/**
 * @brief Списание уценки при выдаче (requirement 76, вопрос 4; для заказов
 * поставщика — решение владельца 10.09.2026, p.mkt.supply).
 *
 * Имущество оприходовано на счёт 10 по цене прибытия, а выдано пайщику могло
 * быть дешевле: остаток кооператива публикуется с уценкой, а брак внутри
 * неделимой упаковки оператор отражает ценой на месте. `issueact2`
 * (o.mkt.consum) закрывает Кт 10 только на фактическую сумму выдачи — без
 * этого действия разница зависала бы на складе, которого физически уже нет.
 * Здесь разница выбывает в прочие расходы:
 *
 *  - `o.mkt.loss` (NONE, Дт 91 / Кт 10) — кошельки не двигаются, чисто
 *    бухгалтерская проводка на сумму уценки.
 *
 * Вместе consum + loss дают выбытие по полной стоимости прибытия. Накопленный
 * расход на счёте 91 погашается ПОЗЖЕ отдельным процессом (Дт 86 / Кт 91) по
 * образцу списания скоропорта через решение совета — этот шаг зафиксирован и
 * пока не реализован.
 *
 * Вызывает backend сразу после финализации выдачи: сумму уценки он считает
 * точно по выданным складским позициям (цены прибытия у позиций одного заказа
 * могут отличаться — FIFO-резерв), контракту эта аналитика недоступна.
 *
 * Guards:
 *  - заказ существует; выдача завершена (status == received) — основание:
 *    двухподписный акт;
 *  - amount > 0 в валюте кооператива;
 *  - идемпотентность: уценка по заказу ещё не списывалась (markdown_cost == 0);
 *  - потолок: по заказу из остатка уценка не больше суммы выдачи (цена
 *    публикации ограничена ценой прибытия); по заказу поставщика уценка вместе
 *    с суммой выдачи не больше принятой стоимости — со склада не выбывает
 *    больше, чем на него пришло по этому заказу.
 *
 * @ingroup public_marketplace_actions
 */
void marketplace::markdown(eosio::name coopname,
                            checksum256 order_hash,
                            eosio::asset amount) {
  require_auth(coopname);

  eosio::check(amount.is_valid() && amount.amount > 0,
               "Сумма уценки должна быть больше нуля");
  eosio::check(amount.symbol == _root_govern_symbol,
               "Некорректный символ валюты в сумме уценки");

  auto o = Marketplace::get_order_by_hash_or_fail(coopname, order_hash);
  eosio::check(o.status == OrderStatus::RECEIVED,
               "Уценка списывается после завершения выдачи по акту");
  eosio::check(o.markdown_cost.amount == 0,
               "Уценка по этому заказу уже списана");
  if (o.offerer == coopname) {
    // Остаток: цена публикации ограничена сверху ценой прибытия (только
    // уценка, без наценки), поэтому уценка не больше суммы выдачи.
    eosio::check(amount <= o.fact_cost,
                 "Сумма уценки превышает фактическую сумму выдачи");
  } else {
    // Заказ поставщика: брак может снизить цену сильнее половины, поэтому
    // держится общий потолок — со склада не выбывает больше принятого.
    eosio::check(o.fact_cost + amount <= Marketplace::get_accepted_cost(o),
                 "Уценка вместе с суммой выдачи превышает стоимость, по которой имущество принято кооперативом");
  }

  Ledger2::apply(_marketplace, coopname,
                 operations::marketplace::MARKDOWN_LOSS,
                 processes::marketplace::SUPPLY,
                 amount, o.orderer, o.hash,
                 Marketplace::Memo::get_markdown_loss_memo(o.id));

  Marketplace::update_order(coopname, o.id, [&](auto& upd) {
    upd.markdown_cost = amount;
  });
}
