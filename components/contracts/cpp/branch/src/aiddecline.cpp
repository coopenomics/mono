/**
 * @brief Callback от gateway — попытка отменить выплату материальной помощи
 * (requirement b6 «Экономика КУ», процесс p.brn.aid).
 *
 * Действие обязано существовать: `Gateway::create_outcome` требует имя
 * decline-callback'а в сигнатуре, иначе исходящий платёж не зарегистрировать.
 * Но отмены в этом процессе нет — действие всегда падает.
 *
 * Почему. Выплату материальной помощи разрешает совет (`onaidauth`), и кассир
 * это решение не пересматривает: принятое решение исполняется. Единственная
 * реальная причина «не смог заплатить» — неверные реквизиты получателя; она
 * решается уточнением реквизитов у получателя, а не отменой решения совета.
 * Отказ до выплаты возможен только на стороне совета — через `onaiddecl`,
 * пока заявление в статусе proposed.
 *
 * @ingroup public_branch_actions
 */
[[eosio::action]] void branch::aiddecline(eosio::name coopname,
                                           eosio::checksum256 outcome_hash,
                                           std::string reason) {
  require_auth(_gateway);

  eosio::check(false,
               "Отмена выплаты материальной помощи невозможна: решение совета о выплате принято и "
               "не пересматривается. При неверных реквизитах уточните их у получателя и проведите перевод.");
}
