/**
 * \brief Прекратить признание: убрать запись о заверении.
 * \ingroup public_ano_actions
 *
 * Действие называется отзывом, но отзывом в строгом смысле не является, и это
 * важно понимать. Подписанное заверение уже у того, кому его выдали; забрать
 * подпись назад нельзя, и проверяющий без сети продолжит принимать её до конца
 * срока. Убрав запись, заверяющий прекращает продление — заверение погаснет
 * само в пределах своего срока, месяца или меньше.
 *
 * Проверяющему с сетью таблица даёт последнее слово: записи нет — признания
 * нет, и ждать истечения незачем.
 *
 * Убрать запись может выдавший её либо АНО. Второе — чтобы ошибку оператора
 * было кому исправить, не дожидаясь его самого.
 */
void ano::revoke(eosio::name issuer, eosio::name subject) {
  require_auth(issuer);

  endorsements_index endorsements(get_self(), get_self().value);

  auto it = endorsements.find(subject.value);
  eosio::check(it != endorsements.end(), "Заверения нет — убирать нечего");
  eosio::check(it->issuer == issuer || issuer == _ano,
               "Убрать заверение может только выдавший его либо АНО");

  endorsements.erase(it);
}
