/**
 * \brief Опубликовать новую версию единой схемы весов репутации.
 * \ingroup public_ano_actions
 *
 * Схема весов определяет, во что превращаются события участия, — то есть
 * реальные начисления людям. Правила такого веса меняются только гласно:
 * новой версией в цепи, действующей вперёд.
 *
 * Кто вправе публиковать. Только АНО — владелец единой схемы сети (решение
 * D5 архитектуры платформы сообщества). Кооперативы предлагают веса своим
 * типам событий организационно; в цепь предложение попадает рукой АНО.
 *
 * Почему номер версии передаётся явно, а не берётся «последний плюс один».
 * Публикация идёт инструментом schema:sync из файла в репозитории: файл
 * называет версию, которую публикует. Если тем временем опубликована другая
 * версия, ожидание разошлось с реальностью — и правильное поведение здесь
 * не молча сдвинуть номер, а отказать: пусть публикующий перечитает
 * действующую схему и осознанно повторит. Это же делает действие безопасным
 * для ретраев: повтор с тем же номером упирается в «версия уже занята».
 *
 * Почему нет действий правки и удаления. Начисленное по опубликованной
 * версии не пересматривается; исправление ошибки в схеме — следующая версия.
 */
void ano::pubrepschema(uint64_t version, std::string document) {
  require_auth(_ano);

  eosio::check(!document.empty(), "Пустая схема — не схема: публиковать нечего");
  eosio::check(document.size() <= MAX_SCHEMA_SIZE,
               "Схема неправдоподобно велика: в таблице норм не место произвольным вложениям");

  repschemas_index schemas(get_self(), get_self().value);

  uint64_t expected = 1;
  auto it = schemas.rbegin();
  if (it != schemas.rend()) {
    expected = it->version + 1;
  }
  eosio::check(version == expected,
               version < expected ? "Версия уже занята: повторная публикация отклонена"
                                  : "Версии растут без пропусков: публикуй следующую по порядку");

  schemas.emplace(get_self(), [&](auto &row) {
    row.version = version;
    row.document = std::move(document);
    row.published_at = eosio::time_point_sec(eosio::current_time_point().sec_since_epoch());
  });
}
