namespace Ano {

/**
 * Предельный срок корневого заверения — пять лет.
 *
 * Заверений такого рода единицы, каждое выдаётся вручную и является событием.
 * Срок здесь длинный сознательно: пересматривать признание оператора раз в
 * месяц незачем, а требовать этого — значит гарантировать, что однажды его
 * забудут продлить и сеть встанет.
 *
 * \ingroup public_ano_consts
 */
static constexpr uint64_t ROOT_ENDORSEMENT_MAX_SECONDS = 5 * 365 * 86400;

/**
 * Предельный срок обычного заверения — месяц с небольшим запасом.
 *
 * Это не срок годности кооператива, а мера того, как быстро срабатывает отзыв.
 * Отозвать выданную подпись невозможно, поэтому единственный способ перестать
 * признавать — перестать продлевать и дождаться, пока последнее заверение
 * погаснет само. Верхняя граница здесь и определяет, сколько это займёт, и
 * потому она в контракте, а не в настройке: заверяющий не должен иметь
 * возможности выдать себе бессрочное признание.
 *
 * Запас над месяцем нужен, чтобы продление, назначенное на тридцатый день,
 * не упиралось в границу из-за времени обработки.
 *
 * \ingroup public_ano_consts
 */
static constexpr uint64_t ENDORSEMENT_MAX_SECONDS = 31 * 86400;

/**
 * Предел размера подписанного заверения.
 *
 * Заверение с его немногими полями укладывается в несколько сотен байт, и
 * порог здесь — не экономия памяти (её оплачивает сам заверяющий), а признак
 * того, что в поле кладут не то, что задумано. Таблица цепочки доверия не
 * место для произвольных вложений.
 *
 * \ingroup public_ano_consts
 */
static constexpr size_t MAX_CREDENTIAL_SIZE = 2048;

/**
 * Предел размера JSON схемы весов репутации.
 *
 * Действующая схема с описаниями типов занимает около десяти килобайт;
 * запас впятеро покрывает рост словаря на годы вперёд. Порог, как и у
 * заверений, — признак того, что в поле кладут не то, что задумано.
 *
 * \ingroup public_ano_consts
 */
static constexpr size_t MAX_SCHEMA_SIZE = 51200;

} // namespace Ano

class [[eosio::contract(ANO)]] ano : public eosio::contract {

public:
  ano(eosio::name receiver, eosio::name code, eosio::datastream<const char *> ds)
      : eosio::contract(receiver, code, ds) {}

  /**
   * \brief Выдать или продлить заверение.
   *
   * \param issuer      кто заверяет: АНО либо оператор, у которого есть
   *                    действующее заверение.
   * \param subject     кого заверяют.
   * \param chain_id    сеть, в которой действует заверение.
   * \param cert_key    ключ заверения субъекта, который признаётся.
   * \param expires_at  когда заверение перестаёт действовать.
   * \param credential  подписанное заверение целиком — то, что поедет внутри
   *                    удостоверения пайщика и будет проверено без сети.
   *
   * \note Авторизация: @p issuer.
   */
  [[eosio::action]] void endorse(eosio::name issuer,
                                 eosio::name subject,
                                 eosio::checksum256 chain_id,
                                 eosio::public_key cert_key,
                                 eosio::time_point_sec expires_at,
                                 std::string credential);

  /**
   * \brief Прекратить признание: убрать запись о заверении.
   *
   * \note Авторизация: заверяющий из записи либо АНО.
   */
  [[eosio::action]] void revoke(eosio::name issuer, eosio::name subject);

  /**
   * \brief Опубликовать новую версию единой схемы весов репутации.
   *
   * \param version   номер публикуемой версии — строго следующий по порядку.
   * \param document  полный JSON схемы (валидируется оффчейн schema-contract).
   *
   * \note Авторизация: только АНО — владелец единой схемы сети.
   */
  [[eosio::action]] void pubrepschema(uint64_t version, std::string document);

  /**
   * \brief Миграция контракта.
   * \note Авторизация: @ ano @ active.
   */
  [[eosio::action]] void migrate();
};
