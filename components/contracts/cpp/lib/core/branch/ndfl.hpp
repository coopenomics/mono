#pragma once

#include <eosio/asset.hpp>
#include <eosio/eosio.hpp>

/**
 * @brief Удержание НДФЛ с материальной помощи доверенному кооперативного
 * участка (requirement b6 «Экономика КУ», процесс p.brn.aid).
 *
 * Решение владельца 2026-08-13 отменяет прежний порядок «налог платит
 * получатель сам» (requirement b6 п. 9): кооператив выступает налоговым
 * агентом — удерживает налог из выплаты и сам перечисляет его в бюджет.
 *
 * Считаем от суммы заявления (брутто): заявление на 10 000 ₽ означает, что с
 * персонального кошелька списывается 10 000 ₽, получателю уходит 8 700 ₽, а
 * 1 300 ₽ остаются обязательством перед бюджетом на счёте 68. Деньги при
 * удержании с расчётного счёта не уходят — кооператив просто выплатил меньше;
 * гасится долг отдельным платежом бухгалтера (o.brn.taxpay).
 *
 * Вычеты не применяются: получатель — доверенное лицо участка, а не работник
 * кооператива, поэтому освобождение первых 4 000 ₽ материальной помощи
 * (п. 28 ст. 217 НК РФ) к нему не относится. Облагается вся сумма.
 *
 * Ставка фиксированная — 13 %. Прогрессивная шкала здесь не считается: суммы
 * материальной помощи до её порогов не дотягивают, а нарастающий итог по году
 * потребовал бы хранить историю доходов пайщика на контракте.
 */
namespace BranchNdfl {

/// Ставка налога на доходы физических лиц, процентов.
inline constexpr int64_t RATE_PERCENT = 13;

/**
 * @brief Сумма налога, удерживаемая из материальной помощи.
 *
 * Налог исчисляется в полных рублях (п. 6 ст. 52 НК РФ): сумма менее
 * 50 копеек отбрасывается, 50 копеек и более округляются до полного рубля.
 * Поэтому считаем не «13 % в минорных единицах», а долю рубля с округлением
 * к ближайшему — иначе в бюджет ушли бы копейки, которых налоговая не ждёт.
 *
 * Умножение делается до деления, чтобы не терять точность на целочисленной
 * арифметике; переполнение int64 недостижимо (13 × сумма заявления).
 *
 * @param gross сумма заявления (положительная, валюта кооператива)
 * @return сумма налога в той же валюте, кратная рублю
 */
inline eosio::asset calc_tax(const eosio::asset& gross) {
  eosio::check(gross.is_valid(), "Некорректная сумма для расчёта налога");
  eosio::check(gross.amount >= 0, "Сумма для расчёта налога не может быть отрицательной");

  // Единица «один рубль» в минорных единицах символа: 10^precision.
  int64_t rouble = 1;
  for (uint8_t i = 0; i < gross.symbol.precision(); ++i) rouble *= 10;

  const int64_t numerator   = gross.amount * RATE_PERCENT;
  const int64_t denominator = 100 * rouble;
  const int64_t roubles     = (numerator + denominator / 2) / denominator;

  return eosio::asset(roubles * rouble, gross.symbol);
}

/**
 * @brief Сумма к перечислению получателю — заявление за вычетом налога.
 *
 * Именно она уходит кассиру в исходящий платёж и списывается операцией
 * o.brn.aid; удержанное проводится парной o.brn.aidtax.
 */
inline eosio::asset calc_net(const eosio::asset& gross) {
  const eosio::asset tax = calc_tax(gross);
  eosio::check(tax.amount < gross.amount,
               "Сумма материальной помощи слишком мала: после удержания налога выплачивать нечего");
  return gross - tax;
}

} // namespace BranchNdfl
