/**
 * @brief Указание оператора, который обслуживает кооператив.
 *
 * Поле «родитель» в реестре кооперативов существовало с самого начала, но не
 * заполнялось ничем и никогда: ни одно действие в него не писало. Задумано оно
 * было не под организационную дочернюю структуру — кооперативы друг друга не
 * учреждают, и такой связи в кооперации попросту нет, — а под ту единственную
 * связь, которая между ними действительно есть: кто чью установку держит.
 *
 * Это действие и придаёт полю смысл. Родитель — оператор, развернувший установку
 * платформы для кооператива. Пустой родитель означает, что кооператив держит
 * установку сам и, стало быть, сам себе оператор.
 *
 * Зачем связь нужна. Оператор обязан продлевать заверения обслуживаемым
 * кооперативам, иначе их удостоверения перестают проходить проверку. Обходить их
 * по расписанию он может, только зная, кто это. Спрашивать об этом сам
 * кооператив нельзя: тогда любой объявил бы себя обслуживаемым и получил
 * заверение, ничего не подписывая.
 *
 * Поэтому подписывают оба: кооператив соглашается на обслуживание, оператор берёт
 * на себя обязательство. Одной подписи не хватает ни с одной стороны. Оператор в
 * одиночку иначе объявил бы себя обслуживающим любой кооператив, у которого
 * оператор ещё не указан, а кооператив в одиночку — навязал бы себя оператору,
 * который о нём не знает, и тот принялся бы его заверять.
 *
 * Провайдер платформы может назначить оператора один — он и так администрирует
 * реестр, и через него проходит перевод уже подключённых кооперативов, у которых
 * оператор не был указан никогда.
 *
 * @param coopname Кооператив, которому назначается оператор
 * @param operator_name Оператор, берущий кооператив на обслуживание
 * @ingroup public_actions
 * @ingroup public_registrator_actions
 *
 * @note Авторизация: @p coopname и @p operator_name вместе, либо провайдер один.
 *       При смене оператора — дополнительно прежний оператор.
 */
[[eosio::action]] void registrator::setoperator(eosio::name coopname, eosio::name operator_name)
{
  if (!has_auth(_provider)) {
    require_auth(coopname);
    require_auth(operator_name);
  }

  eosio::check(coopname != operator_name,
               "Кооператив не может быть оператором самому себе: собственная установка обозначается пустым оператором");

  cooperatives2_index coops(_registrator, _registrator.value);

  auto coop = coops.find(coopname.value);
  eosio::check(coop != coops.end(), "Кооператив не найден");
  eosio::check(coop->is_cooperative, "Организация не является кооперативом");

  // Оператор — тоже кооператив в реестре, и притом действующий: обслуживать чужие
  // установки, не будучи действующим самому, значит обещать то, чего не выполнишь.
  auto oper = coops.find(operator_name.value);
  eosio::check(oper != coops.end(), "Оператор не найден в реестре кооперативов");
  eosio::check(oper->is_cooperative, "Оператор не является кооперативом");
  eosio::check(oper->status.has_value() && oper->status.value() == "active"_n,
               "Оператор не действует — обслуживать кооперативы он не может");

  const eosio::name current = coop->parent_username;
  if (current != eosio::name() && current != operator_name)
    eosio::check(has_auth(current) || has_auth(_provider),
                 "Кооператив обслуживает другой оператор: передачу подписывают оба");

  if (current == operator_name)
    return;

  coops.modify(coop, eosio::same_payer, [&](auto &row) {
    row.parent_username = operator_name;
  });
}
