/**
 * @brief Переводит в просрочку займы, срок возврата которых прошёл.
 *
 * Срок возврата назначается при выдаче займа. Просрочка ничего не отнимает
 * у пайщика: заём по-прежнему закрывается возвратом денег или сдачей
 * результата — но кооператив видит, по каким займам срок вышел.
 *
 * Операцию вызывает кооператив по расписанию — раз в сутки. За один вызов
 * переводится не больше двадцати пяти займов, чтобы уложиться в лимит
 * транзакции; вызывающая сторона повторяет, пока переводить станет нечего.
 *
 * @param coopname Наименование кооператива
 * @ingroup public_actions
 * @ingroup public_capital_actions
 *
 * @note Авторизация требуется от аккаунта: @p coopname.
 */
void capital::markdebtoverd(name coopname) {
  require_auth(coopname);

  constexpr uint32_t MAX_PER_BATCH = 25;
  Capital::Debts::sweep_overdue(coopname, MAX_PER_BATCH);
}
