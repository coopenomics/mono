#!/usr/bin/env bash
# Компиляция всех контрактов кооперативной экономики через CDT.
#
# ВАЖНО: скрипт запускается УЖЕ внутри окружения с установленным CDT —
# тулчейн ожидается по пути /cdt/build/lib/cmake/cdt/CDTWasmToolchain.cmake
# (он захардкожен в CMakeLists.txt). Здесь НЕТ docker — только cmake/make.
#
# Два способа подготовить это окружение:
#   - локально:  build-all.sh оборачивает скрипт в `docker run dicoop/blockchain:latest`
#                (в образе CDT уже лежит в /cdt/build);
#   - в CI:      CDT ставится из .deb (C9S/cdt), а /cdt/build симлинкуется на
#                /usr/opt/cdt/<ver> (см. .github/workflows/release.yaml).
#
# Один источник cmake-флагов для обоих путей — чтобы локальная и CI-сборка
# не разъезжались.
set -euo pipefail

mode="${1:-prod}"
if [ "$mode" = "test" ]; then
  is_testnet="ON"
else
  is_testnet="OFF"
fi

mkdir -p build

# ── Кэш сборки сверяется по содержимому, а не по времени ─────────────────────
#
# make решает, что пересобирать, по mtime. В обычной работе этого достаточно:
# `git checkout` ставит исходнику время «сейчас», поэтому он оказывается новее
# объектника и пересборка происходит сама.
#
# Ломается это при переносе каталога `build` между стендами. Он лежит вне git,
# весит ~20 МБ, а пути внутри CDT-контейнера у всех стендов одинаковые
# (`/project`), поэтому копировать его быстрее, чем собирать заново — сорок
# минут против минут. Но объектники приезжают с чужим, более поздним временем,
# и make молча признаёт свежими wasm'ы, собранные совсем из другого кода.
# Наружу это выходит как «правлю контракт, пересобираю, а в цепи ничего не
# меняется» — то есть никак.
#
# Поэтому рядом с объектниками лежит манифест хэшей исходников, из которых они
# собраны, и он переезжает вместе с ними. Перед сборкой трогаем файлы, чьё
# содержание с манифестом разошлось; дальше make работает как обычно и
# пересобирает только затронутое, включая зависящее по заголовкам.
#
# Манифеста нет (сборка с нуля) — шаг ничего не делает.
MANIFEST="build/.sources.sha256"

if [ -f "$MANIFEST" ]; then
  # sha256sum -c возвращает ненулевой код при первом же расхождении — это здесь
  # штатная ситуация, а не ошибка, поэтому код не проверяем (при set -e с
  # pipefail иначе упадём ровно там, где расхождение и искали).
  stale="$({ sha256sum -c "$MANIFEST" 2>/dev/null || true; } | sed -n 's/: FAILED$//p')"

  if [ -n "$stale" ]; then
    echo "▸ Содержание разошлось с кэшем сборки — помечаю к пересборке:"
    while IFS= read -r file; do
      # Удалённые файлы пропускаем: их отсутствие make заметит сам.
      [ -f "$file" ] || continue
      echo "    $file"
      touch "$file"
    done <<< "$stale"
  fi
fi

cd build
cmake -DBUILD_TARGET= -DTEST_TARGET= -DVERBOSE=ON -DBUILD_TESTS=OFF -DIS_TESTNET="$is_testnet" ..
make
cd ..

# Манифест пишем только после успешной сборки: иначе следующий запуск счёл бы
# собранным то, что упало на середине.
find cpp CMakeLists.txt -type f -print0 | sort -z | xargs -0 sha256sum > "$MANIFEST"
