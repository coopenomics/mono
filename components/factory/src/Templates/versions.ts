/**
 * Реестр версий шаблонов документов.
 *
 * Версия шаблона — это требование к подписи, а не номер редакции текста.
 * Рабочий стол пайщика сверяет версию шаблона в реестре с версией, под
 * которой пайщик подписался, и при расхождении просит подписать заново
 * (виджет `RequireAgreements`). Поэтому:
 *
 * - правка текста, вёрстки, опечатки, отступа — **версию не трогаем**.
 *   Синхронизатор просто перезальёт содержание (`editdraft`/`edittrans`),
 *   и никто ничего не переподписывает;
 * - изменение смысла (условия, права, обязанности, состав сведений) —
 *   поднимаем здесь число на единицу. Тогда при ближайшей раскатке
 *   синхронизатор вызовет `upversion`, и все пайщики получат требование
 *   подписать документ заново.
 *
 * Число здесь — целевая версия. Синхронизатор поднимает версию в сети до
 * этого значения и никогда не опускает: если в какой-то сети версия уже
 * выше объявленной, документ не трогается, а в отчёте появляется
 * предупреждение — значит следующее объявленное значение надо брать выше
 * фактического.
 *
 * Документы, которых здесь нет, считаются версией {@link DEFAULT_TEMPLATE_VERSION}.
 *
 * Значения засеяны с производственной сети (`api.coopenomics.world`)
 * 2026-08-09 — так первая раскатка реестра никому не назначает
 * переподписи. В тестовой сети часть документов на этот момент имела
 * версии выше (переподписи там запрашивались чаще) — они так и остались
 * выше, синхронизатор их не понижает.
 */
export const DEFAULT_TEMPLATE_VERSION = 1

export const TemplateVersions: Record<number, number> = {
  1: 3, // Согласие с условиями ЦПП «Цифровой кошелёк»
  2: 3, // Регламент электронной подписи
  3: 3, // Политика конфиденциальности
  4: 3, // Пользовательское соглашение
  50: 3, // Соглашение с Коопеномикой
  100: 7, // Заявление о вступлении в кооператив
  101: 4, // Заявление о выборе кооперативного участка
  501: 3, // Решение по заявлению о вступлении
  599: 3, // Свободное решение по проекту
  600: 2, // Свободное решение
}

/**
 * Целевая версия шаблона документа.
 */
export function getTemplateVersion(registry_id: number | string): number {
  return TemplateVersions[Number(registry_id)] ?? DEFAULT_TEMPLATE_VERSION
}
