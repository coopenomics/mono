/**
 * Откуда фабрика документов берёт данные цепи.
 *
 * Сама она их не добывает: раньше фабрика ходила по HTTP в обозреватель
 * старого парсера, из-за чего библиотека генерации документов знала про
 * конкретный сервис и не могла работать без него. Теперь потребность объявлена
 * интерфейсом, а откуда читать — решает тот, кто фабрику создаёт: узел отдаёт
 * реализацию поверх собственной базы, а инструменты развёртывания — поверх
 * прямых запросов к цепи.
 *
 * Про `block_num`: документ, подписанный когда-то, обязан пересобираться теми
 * данными, что действовали на момент подписи, иначе изменится его содержимое
 * при неизменном хэше. Реализация, которая историю не хранит, обязана честно
 * отдать текущее состояние — но не притворяться, что вернула историческое.
 */

/** Запрос строк он-чейн таблицы. */
export interface ITableQuery {
  /** Аккаунт контракта. */
  code: string
  /** Скоуп таблицы (обычно имя кооператива либо сам контракт). */
  scope: string
  /** Имя таблицы. */
  table: string
  /**
   * Отбор по полям строки. Ключ — имя поля верхнего уровня либо путь через
   * точку (`document.doc_hash`), значение сравнивается как строка.
   */
  filter?: Record<string, unknown>
  /** Состояние на этот блок; не задан — текущее. */
  block_num?: number
  /** Сколько строк вернуть. */
  limit?: number
}

/** Запрос действий из истории цепи. */
export interface IActionQuery {
  /** Аккаунт контракта. */
  account: string
  /** Имя действия. */
  name?: string
  /** Отбор по полям полезной нагрузки — как у таблиц. */
  data?: Record<string, unknown>
  limit?: number
}

export interface IChainDataSource {
  /** Строки таблицы под условие; порядок — от свежих блоков к старым. */
  getTableRows: <T = any>(query: ITableQuery) => Promise<T[]>

  /**
   * Действия под условие; порядок — от свежих к старым.
   *
   * Историю действий хранит только тот, кто её накапливает. Реализация поверх
   * прямых запросов к цепи такой истории не имеет и вернёт пусто — это
   * осознанное ограничение, а не сбой: документы, которым нужны голоса совета,
   * собираются узлом, а не инструментом развёртывания.
   */
  getActions: <T = any>(query: IActionQuery) => Promise<T[]>

  /** Текущая высота цепи — попадает в метаданные документа. */
  getCurrentBlock: () => Promise<number>
}

