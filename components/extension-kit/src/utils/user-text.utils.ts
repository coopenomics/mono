import { _Common } from 'cooptypes';

/**
 * Очистка текста, который человек пишет в редакторе: описание проекта или
 * задачи, приглашение, краткое содержание звонка.
 *
 * Правило одно на кабинет и сервер и живёт в `cooptypes`; здесь — только
 * удобная точка вызова для расширений и обработка пустых значений. До
 * 17.09.2026 очистка стояла лишь в редакторе, поэтому запрос напрямую в API
 * клал в базу произвольную разметку, а она потом попадала в собираемые
 * документы.
 *
 * Правило намеренно мягкое: описание живёт вперемешку с разметкой, таблицами и
 * схемами BPMN — убирается только исполняемое.
 */
export function sanitizeUserText<T extends string | null | undefined>(value: T): T {
  if (typeof value !== 'string' || !value) return value;
  return _Common.Text.sanitizeEditorMarkdown(value) as T;
}
