/**
 * Срок, отпущенный расширению на подключение к кооперативу.
 *
 * Совет проходит шаги подключения не за один присест, поэтому у начатого
 * подключения есть срок годности: по его истечении расширение считает
 * подключение просроченным и предлагает начать заново. Политика общая для всех
 * расширений — раньше срок был захардкожен в двух модулях порознь и рисковал
 * разойтись.
 */
export const ONBOARDING_EXPIRY_DAYS = 30;

export const ONBOARDING_EXPIRY_MS = ONBOARDING_EXPIRY_DAYS * 24 * 60 * 60 * 1000;

/**
 * Момент истечения, отсчитанный от начала подключения. Возвращает строку ISO:
 * в настройке расширения срок хранится строкой.
 */
export function computeOnboardingExpiresAt(startedAt: Date): string {
  return new Date(startedAt.getTime() + ONBOARDING_EXPIRY_MS).toISOString();
}
