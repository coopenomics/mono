/**
 * Настройки контура, одинаковые для всех расширений и не содержащие секретов.
 *
 * Расширение обязано знать, в каком кооперативе оно работает и по какому адресу
 * его открывают, — иначе оно не соберёт ни ссылку в уведомлении, ни имя счёта.
 * Раньше за этим шли прямо в `~/config/config` контроллера, то есть по пути,
 * которого за пределами монолита не существует.
 *
 * **Здесь только то, что не жалко отдать любому расширению.** Ни ключей, ни
 * паролей, ни реквизитов доступа тут нет и быть не должно. Именно поэтому
 * настройки раздаются простой функцией, а не портом с DI: гейт capability
 * (какому расширению что доступно) имеет смысл ровно там, где есть что
 * закрывать. Имя кооператива закрывать не от кого — оно нужно всем и не
 * является тайной.
 *
 * Секретное и инфраструктурное — ключи Matrix, LiveKit, OpenAI, токен GitHub —
 * через этот канал не проходит принципиально. Им положен явный порт под
 * capability-гейтом, и до его появления они остаются там, где лежат.
 */
export interface PlatformBlockchainSettings {
  /** Символ базового токена управления кооператива, например `RUB`. */
  rootGovernSymbol: string;
  /** Точность базового токена — знаков после запятой. */
  rootGovernPrecision: number;
}

export interface PlatformSettings {
  /** Учётное имя кооператива в цепи, например `voskhod`. */
  coopname: string;
  /** Адрес, по которому пайщик открывает кооператив; основа для ссылок в уведомлениях. */
  frontendUrl: string;
  /** Адрес API контура. */
  backendUrl: string;
  /** Часовая зона кооператива в формате IANA, например `Europe/Moscow`. */
  timezone: string;
  blockchain: PlatformBlockchainSettings;
}

let settings: PlatformSettings | undefined;

/**
 * Задать настройки контура. Вызывается composition root'ом один раз при старте,
 * до того как приложение начнёт принимать запросы.
 */
export function configurePlatformSettings(value: PlatformSettings): void {
  settings = Object.freeze({ ...value, blockchain: Object.freeze({ ...value.blockchain }) });
}

/**
 * Прочитать настройки контура.
 *
 * Бросает, если настройки не заданы. Молчаливый возврат пустых значений был бы
 * хуже: расширение построило бы ссылку на несуществующий адрес или создало
 * запись с пустым именем кооператива, и разбирались бы мы уже с последствиями.
 */
export function platformSettings(): PlatformSettings {
  if (!settings) {
    throw new Error(
      'Настройки контура не заданы: composition root обязан вызвать configurePlatformSettings() при старте'
    );
  }
  return settings;
}
