/**
 * Запись зеркала цепи в базе узла: общие колонки всех таблиц, которые
 * синхронизируются с блокчейном. Обычный класс без привязки к прослойке базы —
 * таблицу, ключ и json-колонки задаёт шлюз таблицы (`TableStore`).
 */
export class ChainRecord {
  _id!: string;

  /** Блок последнего изменения из цепи; у записи, созданной до синхронизации, — 0. */
  block_num!: number;

  /** Есть ли запись в цепи сейчас. */
  present!: boolean;

  status!: string;

  _created_at!: Date;

  _updated_at!: Date;
}
