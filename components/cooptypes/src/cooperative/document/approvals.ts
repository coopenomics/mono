/**
 * Утверждение редакций шаблонов документов советом кооператива.
 *
 * Перечисления общие для контроллера и рабочего стола: контроллер вычисляет
 * состояние документа в кооперативе, рабочий стол показывает его во вкладке
 * «Шаблоны документов» и в карточках подключения приложений.
 */

/** Род документа в реестре шаблонов кооператива. */
export enum DocumentKind {
  /** Подписывают пайщики: политика, оферты ЦПП, соглашение о кошельке. Новая редакция требует переподписания. */
  Agreement = 'agreement',
  /** Утверждает совет, пайщики не подписывают: положения ЦПП, шаблоны договоров. */
  Provision = 'provision',
  /** Заявления, акты, накладные: утверждается как форма, экземпляры порождаются по событиям. */
  Form = 'form',
  /** Повестка, протоколы, бюллетени: форма задана уставом или законом, утверждение не требуется. */
  Service = 'service',
}

/** Нужно ли решение совета, чтобы редакция документа действовала в кооперативе. */
export enum DocumentApprovalRequirement {
  Required = 'required',
  None = 'none',
}

/** Состояние документа в кооперативе относительно редакции в сети. */
export enum DocumentApprovalState {
  /** Утверждение не требуется (служебный документ). */
  NotRequired = 'not_required',
  /** Совет ещё ни одной редакции не утверждал. */
  NotApproved = 'not_approved',
  /** Проект решения об утверждении в повестке совета. */
  Pending = 'pending',
  /** Утверждённая редакция совпадает с редакцией в сети. */
  Approved = 'approved',
  /** В сети вышла редакция новее утверждённой, решения совета ещё нет. */
  Outdated = 'outdated',
}
