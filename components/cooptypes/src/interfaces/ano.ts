// Соответствует contracts/cpp/ano/ano.abi.
// Написано вручную: набор полей мал и стабилен, а осмысленные комментарии
// генератор не сохраняет.

export type IName = string
export type IChecksum256 = string
export type IPublicKey = string
export type ITimePointSec = string

// ── Таблицы ────────────────────────────────────────────────────────────────

/**
 * Заверение: заверяющий признаёт, что субъект вправе заверять этим ключом.
 *
 * Одна запись описывает оба уровня цепочки: АНО заверяет оператора, оператор —
 * кооператив. Различаются такие записи только тем, кто указан заверяющим.
 *
 * `credential` — подписанное заверение целиком, то самое, что поедет внутри
 * удостоверения пайщика. Остальные поля дублируют подписанное содержимое, чтобы
 * искать и отбирать записи, не разбирая подпись на каждой.
 */
export interface IEndorsement {
  subject: IName
  issuer: IName
  chain_id: IChecksum256
  cert_key: IPublicKey
  issued_at: ITimePointSec
  expires_at: ITimePointSec
  credential: string
}

/**
 * Версия единой схемы весов репутации сети.
 *
 * Полный JSON схемы лежит в записи целиком (образец — draft::drafts): цепь —
 * единственный источник нормы, по которой считаются начисления. Версии только
 * растут; действующая — запись с наибольшим номером. Содержимое JSON контракт
 * не разбирает — формат валидируется оффчейн пакетом schema-contract.
 */
export interface IRepSchema {
  version: number
  document: string
  published_at: ITimePointSec
}

// ── Действия ───────────────────────────────────────────────────────────────

/**
 * Выдать или продлить заверение.
 *
 * Заверять вправе АНО и всякий, у кого есть действующее заверение. Срок
 * ограничен сверху: пять лет для корневых заверений, месяц для остальных —
 * отозвать выданную подпись нельзя, и предел срока определяет, как быстро
 * перестанет действовать то, что перестали продлевать.
 */
export interface IEndorse {
  issuer: IName
  subject: IName
  chain_id: IChecksum256
  cert_key: IPublicKey
  expires_at: ITimePointSec
  credential: string
}

/**
 * Прекратить признание: убрать запись о заверении.
 *
 * Отзывом в строгом смысле не является — выданная подпись остаётся у того, кому
 * её выдали, и проверяющий без сети примет её до конца срока. Убранная запись
 * прекращает продление и даёт последнее слово проверяющему, у которого сеть есть.
 */
export interface IRevoke {
  issuer: IName
  subject: IName
}

export interface IMigrate {}

/**
 * Опубликовать новую версию единой схемы весов репутации.
 *
 * Авторизация — только АНО, владелец единой схемы сети. Номер версии — строго
 * следующий по порядку: повтор занятой версии и пропуск отклоняются, поэтому
 * ретраи публикации безопасны.
 */
export interface IPubrepschema {
  version: number
  document: string
}
